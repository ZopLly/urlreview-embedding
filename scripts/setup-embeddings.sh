#!/bin/sh
# О файле: Явная установка необязательных зависимостей и скачивание модели. Этот скрипт обращается в сеть; обычный запуск приложения этого не делает.
# Пояснение: Любая необработанная ошибка или незаданная переменная завершает скрипт.
set -eu
# Пояснение: Переходим в каталог проекта.
cd "$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
# Пояснение: Если PYTHON_BIN отсутствует или пуст, попробуем выбрать подходящий Python автоматически.
if [ -z "${PYTHON_BIN:-}" ]; then
    # Пояснение: Начальный запасной кандидат — команда python3.
    PYTHON_BIN=python3
    # Пояснение: Предпочтительный перебор поддерживаемых отдельных версий интерпретатора.
    for candidate in python3.12 python3.13 python3.11; do
        # Пояснение: Первый найденный executable сохраняем и прекращаем поиск; вывод поиска подавлен.
        if command -v "$candidate" >/dev/null 2>&1; then PYTHON_BIN=$candidate; break; fi
    # Пояснение: done завершает цикл кандидатов.
    done
# Пояснение: fi завершает автоматический выбор интерпретатора.
fi
# Пояснение: Проверяем диапазон версий 3.11–3.13; sys.exit выводит пояснение, если он не подходит.
"$PYTHON_BIN" -c 'import sys; sys.exit(0 if (3,11) <= sys.version_info[:2] <= (3,13) else "Нужен Python 3.11–3.13. Укажите PYTHON_BIN=/путь/python3.12")'
# Пояснение: Создаём изолированное виртуальное окружение для необязательных библиотек.
"$PYTHON_BIN" -m venv .venv-embeddings
# Пояснение: pip устанавливает закреплённые версии зависимостей из requirements.txt, при необходимости через
# Пояснение: сеть.
.venv-embeddings/bin/python -m pip install -r embeddings/requirements.txt
# Пояснение: Явно вызываем download: скачивание закреплённых модели и токенизатора с проверкой сумм.
.venv-embeddings/bin/python embeddings/local_embeddings.py download
# Пояснение: Запускаем smoke на настоящей установленной модели и вымышленных текстах.
.venv-embeddings/bin/python embeddings/local_embeddings.py smoke
