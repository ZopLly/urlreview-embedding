# О файле: Одноразовое извлечение справочника из PDF через координаты его таблицы. Координаты относятся к предоставленному макету; скрипт не универсальный PDF-парсер.
# Пояснение: Документация модуля: извлечение категорий, без доступа к рабочему набору CSV.
"""Extract the provided category PDF by its table coordinates (no dataset access).

Usage: python3 scripts/extract_guide.py CATEGORY_PDF data/categories.tsv
Requires Poppler pdftotext only when regenerating the supplied guide.
"""
# Пояснение: Подключаем bisect: двоичный поиск категории по отсортированным координатам PDF.
import bisect
# Пояснение: Подключаем re: регулярные выражения для кодов и нормализации пробелов.
import re
# Пояснение: Подключаем subprocess: запуск внешних программ отдельным процессом.
import subprocess
# Пояснение: Подключаем sys: аргументы, stderr и завершение процесса.
import sys
# Пояснение: Подключаем xml.etree.ElementTree: стандартный XML-парсер для вывода pdftotext.
import xml.etree.ElementTree as ET
# Пояснение: Импортируем выбранное имя из pathlib: Path для удобной работы с файловыми путями.
from pathlib import Path

# Пояснение: Главная функция генерации TSV из переданного PDF.
def main():
    # Пояснение: Запускаем Poppler pdftotext в режиме XML с координатами слов; "-" возвращает результат в
    # Пояснение: stdout.
    xml = subprocess.check_output(['pdftotext', '-bbox-layout', sys.argv[1], '-'])
    # Пояснение: Разбираем полученный XML в дерево элементов.
    tree = ET.fromstring(xml)
    # Пояснение: Пространство имён XHTML нужно для поиска тегов страницы и слова.
    ns = {'h': 'http://www.w3.org/1999/xhtml'}
    # Пояснение: Накапливаем все слова и отдельно координатные якоря кодов категорий.
    words, anchors = [], []
    # Пояснение: Обходим страницы по порядку с их номерами.
    for page_number, page in enumerate(tree.findall('.//h:page', ns)):
        # Пояснение: Обходим слова текущей страницы.
        for w in page.findall('.//h:word', ns):
            # Пояснение: Из XML-атрибутов берём левые верхние координаты слова и превращаем в числа.
            x, y = float(w.get('xMin')), float(w.get('yMin'))
            # Пояснение: Пустое содержимое элемента заменяем пустой строкой.
            text = w.text or ''
            # Пояснение: Составляем ключ порядка: номер страницы × 1000 плюс вертикальная координата.
            key = page_number * 1000 + y
            # Пояснение: Сохраняем положение и текст слова.
            words.append((key, x, text))
            # Пояснение: Слово у фиксированной колонки кодов с нужным шаблоном считаем началом категории.
            if abs(x-210.26)<1 and re.fullmatch('[a-z][a-z_0-9]*', text):
                # Пояснение: Запоминаем вертикальный якорь и код этой категории.
                anchors.append((key, text))
    # Пояснение: Сортируем якоря по положению на страницах.
    anchors.sort()
    # Пояснение: Отдельный список ключей нужен для двоичного поиска категории.
    keys = [k for k,_ in anchors]
    # Пояснение: Для каждой категории готовим списки слов названия, включений и исключений.
    fields = [[[],[],[]] for _ in anchors]
    # Пояснение: Слова обходим в порядке координат, получая расположение внутри PDF.
    for key,x,text in sorted(words):
        # Пояснение: Находим последний якорь не ниже key+2; допуск 2 учитывает небольшие вертикальные различия.
        idx = bisect.bisect_right(keys,key+2)-1
        # Пояснение: Слова до первой категории или левее таблицы не используем.
        if idx<0 or x<209:
            # Пояснение: Переходим к следующему слову вне нужной области.
            continue
        # Пояснение: Левая область таблицы содержит код и название.
        if x<379.5:
            # Пояснение: Сам код не повторяем в title, остальные слова добавляем.
            if text != anchors[idx][1]: fields[idx][0].append(text)
        # Пояснение: Средняя область таблицы содержит включения.
        elif x<659.5:
            # Пояснение: Добавляем слово к включениям найденной категории.
            fields[idx][1].append(text)
        # Пояснение: Всё правее относится к исключениям.
        else:
            # Пояснение: Добавляем слово к исключениям.
            fields[idx][2].append(text)
    # Пояснение: Список готовых строк TSV.
    lines=[]
    # Пояснение: Совмещаем якорь категории и три накопленных поля по их позициям.
    for (_,code),(title,inc,exc) in zip(anchors,fields):
        # Пояснение: Собираем название из слов и убираем внешние скобки и пробелы.
        title=' '.join(title).strip('() ')
        # Short code-only categories in the source retain their code as title.
        # Пояснение: Если названия нет, сохраняем сам код как title; ручные краткие пояснения здесь
        # Пояснение: перезапишутся.
        title=title or code
        # Пояснение: Создаём четыре поля строки: код, название, включения, исключения.
        values=[code,title,' '.join(inc),' '.join(exc)]
        # Пояснение: Сжимаем пробельные последовательности внутри полей, соединяем поля табуляцией.
        lines.append('\t'.join(re.sub(r'\s+',' ',v).strip() for v in values))
    # Пояснение: Пишем TSV UTF-8 по второму пути аргументов с финальным переводом строки.
    Path(sys.argv[2]).write_text('\n'.join(lines)+'\n',encoding='utf-8')
    # Пояснение: Сообщаем число извлечённых категорий.
    print(f'{len(lines)} categories extracted')

# Пояснение: Выполняем CLI только при прямом запуске, не при импорте.
if __name__=='__main__':
    # Пояснение: Запускаем извлечение.
    main()
