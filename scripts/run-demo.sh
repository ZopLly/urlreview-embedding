#!/bin/sh
# О файле: Сборка и запуск ручной разметки на вымышленных данных demo/synthetic.csv.
# Пояснение: Завершаем при ошибке или использовании незаданной переменной.
set -eu
# Пояснение: Находим абсолютный корень проекта относительно местоположения этого скрипта.
task_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
# Пояснение: Переходим в корень, чтобы относительные пути следующих команд были корректны.
cd "$task_root"
# Пояснение: Собираем приложение; -s убирает эхо команд make.
make -s
# Пояснение: Создаём results, разрешая уже существующий каталог.
mkdir -p results
# Пояснение: Заменяем shell приложением; исходник — demo, рабочая копия — results/demo-review.csv.
exec ./url-review demo/synthetic.csv results/demo-review.csv
