#!/bin/sh
# О файле: Запускает локальное построение индекса в отдельном Python-окружении; рабочий каталог вызывающего процесса сохраняется для относительных путей CSV.
# Пояснение: -e останавливает скрипт при ошибке команды, -u запрещает обращение к незаданным переменным.
set -eu
# Preserve caller's working directory so relative CSV paths stay meaningful.
# Пояснение: Находим корень относительно скрипта; cd происходит внутри подстановки, не меняя каталог основного
# Пояснение: shell.
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
# Пояснение: Проверяем исполняемость Python из подготовленного окружения.
if [ ! -x "$root/.venv-embeddings/bin/python" ]; then
    # Пояснение: Пишем инструкцию установки в stderr, обозначенный перенаправлением >&2.
    echo 'Сначала запустите scripts/setup-embeddings.sh из папки проекта.' >&2
    # Пояснение: Без Python-окружения завершаем с ошибкой.
    exit 1
# Пояснение: fi завершает условие if.
fi
# Пояснение: exec заменяет shell Python-процессом; "$@" передаёт каждый пользовательский аргумент отдельно,
# Пояснение: сохраняя пробелы.
exec "$root/.venv-embeddings/bin/python" "$root/embeddings/local_embeddings.py" build "$@"
