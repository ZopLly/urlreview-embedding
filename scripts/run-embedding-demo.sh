#!/bin/sh
# О файле: Демо полного пути: C-сборка, локальный индекс по вымышленным описаниям и интерфейс с поиском похожих.
# Пояснение: Ошибки и незаданные переменные останавливают сценарий.
set -eu
# Пояснение: Переходим в корень проекта независимо от каталога запуска скрипта.
cd "$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
# Пояснение: Собираем терминальное приложение.
make -s
# Пояснение: Подготавливаем каталог выходных результатов.
mkdir -p results
# Пояснение: Строим индекс demo.uremb из demo CSV; модель должна быть установлена заранее.
./scripts/build-embeddings.sh demo/synthetic.csv results/demo.uremb
# Пояснение: Запускаем приложение с рабочей копией и только что подготовленным индексом.
exec ./url-review demo/synthetic.csv results/demo-review.csv --embeddings results/demo.uremb
