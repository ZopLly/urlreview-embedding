"""Повторяемая диагностика модели на вымышленных текстах; рабочие файлы не открывает."""
# Импортируем готовый локальный Encoder из соседнего каталога проекта.
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'embeddings'))
from local_embeddings import Encoder

# Категория здесь — эталон контрольного примера, а не предсказание программы.
EXAMPLES = [
    ('Travel', 'Туристическое агентство: туры в Турцию, бронирование гостиниц, экскурсии и авиабилеты.'),
    ('health_and_medicine', 'Стоматологическая клиника: лечение зубов, имплантация, запись к стоматологу.'),
    ('education', 'Образовательный центр: подготовка к экзаменам, курсы английского языка, запись на занятия.'),
    ('catalog_sales', 'Каталог промышленного оборудования. Для покупки станка запросите цену по телефону или отправьте заявку.'),
    ('services', 'Ремонт квартир и строительство домов. Рассчитайте стоимость работ и оставьте заявку мастеру.'),
    ('corporate', 'Машиностроительный завод: история предприятия, производственные мощности, реализованные проекты и контакты.'),
    ('shopping', 'Интернет-магазин смартфонов: добавьте товар в корзину, оплатите заказ картой, доставка по России.'),
    ('NOT_DESC', 'Главная. О компании. Каталог. Услуги. Контакты. Войти. Все права защищены. Согласие на обработку персональных данных.'),
]
# Каждый запрос отличается от эталонного описания той же темы.
QUERIES = [
    ('Travel', 'Бронирование номеров в отеле, стоимость проживания, отдых и экскурсии.'),
    ('health_and_medicine', 'Медицинский центр: приём терапевта, анализы крови, диагностика заболеваний.'),
    ('education', 'Онлайн-школа: курсы для школьников, обучение математике и подготовка к ЕГЭ.'),
    ('catalog_sales', 'Оптовая поставка станков. Прайс по запросу, заказ через менеджера по телефону.'),
    ('services', 'Клининг: уборка офисов, мытьё окон, вызов специалиста и расчёт стоимости.'),
    ('corporate', 'О предприятии: руководство, производство, партнёры, новости компании и контакты.'),
]


def main():
    # Используем уже установленную модель; скачивания и обучения здесь нет.
    encoder = Encoder()
    vectors = [encoder(text) for _, text in EXAMPLES]
    before, after = 0, 0
    for expected, text in QUERIES:
        # Encoder нормализует векторы, поэтому сумма произведений даёт косинус.
        query = encoder(text)
        ranked = sorted(((sum(a*b for a,b in zip(query, vector)), label)
                         for (label, _), vector in zip(EXAMPLES, vectors)), reverse=True)
        # Сравниваем прежний набор кандидатов с новым фильтром подтверждённых категорий.
        eligible = [hit for hit in ranked if hit[1] != 'NOT_DESC']
        before += ranked[0][1] == expected
        after += eligible[0][1] == expected
        print(f'{expected}: до {ranked[0][1]} ({ranked[0][0]:.4f}); после {eligible[0][1]} ({eligible[0][0]:.4f})')
    # Шесть контрольных запросов — диагностический пример, не оценка рабочего датасета.
    print(f'Контрольный top-1: {before}/{len(QUERIES)} → {after}/{len(QUERIES)}. Качество на ваших данных не измерено.')


if __name__ == '__main__':
    main()
