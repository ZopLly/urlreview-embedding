// О файле: Вспомогательный CLI для независимого Python-теста: читает CSV ядром C и пишет сериализованный результат в другой файл.
// Пояснение: Подключаем core.h: общие типы Table/Store и функции CSV, памяти и сохранения.
#include "core.h"
// Пояснение: Подключаем stdio.h: файловые потоки FILE, printf, snprintf и ввод/вывод.
#include <stdio.h>
// Пояснение: Подключаем stdlib.h: выделение и освобождение памяти, exit и другие базовые функции.
#include <stdlib.h>
// Пояснение: Подключаем string.h: strlen, strcmp, memcpy, memset и другие операции строк/байтов.
#include <string.h>
// Пояснение: ОС передаёт аргументы: входной файл, выходной файл, кодировка и разделитель.
int main(int argc,char **argv) {
    // Пояснение: Вместе с именем программы должно быть ровно пять аргументов; 2 означает ошибку вызова.
    if(argc!=5)return 2;
    // Пояснение: Буфер ошибки и структура таблицы.
    char err[ERR_SIZE];Table t;
    // Пояснение: Слово tab переводим в символ табуляции; иначе берём первый байт разделителя.
    char sep=!strcmp(argv[4],"tab")?'\t':argv[4][0];
    // Пояснение: Читаем CSV в указанной кодировке; при ошибке печатаем её и возвращаем 1.
    if(!table_read(argv[1],argv[3],sep,&t,err)){fprintf(stderr,"%s\n",err);return 1;}
    // Пояснение: Сериализуем таблицу во внутренний UTF-8 CSV, получая длину n.
    size_t n,m;char *utf=table_serialize(&t,&n);
    // Пояснение: Возвращаем текст в исходную кодировку; освобождаем промежуточный UTF-8 и таблицу.
    char *out=convert_text(utf,n,"UTF-8",argv[3],&m,err);free(utf);table_free(&t);
    // Пояснение: Неудачная конвертация прерывает тестовую программу.
    if(!out)return 1;
    // Пояснение: Открываем отдельный выходной файл; при ошибке освобождаем результат конвертации.
    FILE *f=fopen(argv[2],"wb");if(!f){free(out);return 1;}
    // Пояснение: Проверяем запись всех m байтов и освобождаем их память.
    bool ok=fwrite(out,1,m,f)==m;free(out);
    // Пояснение: Ошибку fclose тоже считаем неудачей.
    if(fclose(f))ok=false;
    // Пояснение: Возвращаем 0 при полном успехе или 1 при ошибке.
    return ok?0:1;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
