// Пояснение: Подключаем errno.h: errno и коды системных ошибок.
#include <errno.h>
// Пояснение: Подключаем sys/stat.h: метаданные файла и проверки его типа.
#include <sys/stat.h>
// Пояснение: Подключаем unistd.h: POSIX-вызовы read/write/close/fsync и работу с процессами.
#include <unistd.h>
// Пояснение: Объявление настоящей fsync, доступной через --wrap=fsync.
int __real_fsync(int fd);
// Пояснение: Обёртка системного вызова для специального тестового приложения.
int __wrap_fsync(int fd) {
    // Пояснение: Статический счётчик вызовов для каталогов сохраняется между обращениями.
    static int directory_calls;
    // Пояснение: Структура метаданных объекта по дескриптору.
    struct stat st;
    // Пояснение: Первый fsync каталога создаёт копию; второй получает искусственные EIO и -1.
    if(fstat(fd,&st)==0 && S_ISDIR(st.st_mode) && ++directory_calls==2) {errno=EIO;return -1;}
    // Пояснение: Все остальные вызовы выполняются настоящей fsync, поэтому повторная попытка может пройти.
    return __real_fsync(fd);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
