MAX_BYTES = 256 * 1024 * 1024


# Пояснение: Создаёт такой же 64-битный FNV-1a отпечаток записи, как fingerprint в embedding.c.
def fingerprint(domain, description):
    # Пояснение: Начальное значение FNV-1a.
    h = 14695981039346656037
    # Пояснение: Между доменом и описанием ставим нулевой байт, затем перебираем байты UTF-8.
    for byte in (domain + '\0' + description).encode('utf-8'):
        # Пояснение: XOR смешивает байт; умножение и маска 64 бит имитируют переполнение uint64_t из C.
        h = ((h ^ byte) * 1099511628211) & ((1 << 64) - 1)
    # Пояснение: Возвращаем отпечаток, а не вектор смысла текста.
    return h


# Пояснение: Генератор перекрывающихся окон токенов: по умолчанию длина 320, перекрытие 32.
def chunks(tokens, window=320, overlap=32):
    # Пояснение: Окно должно быть положительным, перекрытие — от 0 до window-1.
    if window < 1 or not 0 <= overlap < window:
        # Пояснение: Неверные параметры могли бы дать нулевой или отрицательный шаг: отклоняем их.
        raise ValueError('Invalid token window/overlap')
    # Пояснение: Шаг window-overlap сохраняет часть предыдущего контекста в следующем окне.
    for start in range(0, len(tokens), window - overlap):
        # Пояснение: yield отдаёт срез токенов и приостанавливает генератор до запроса следующего окна.
        yield tokens[start:start + window]
        # Пояснение: Если окно уже охватило конец, дополнительное окно из одного перекрытия не нужно.
        if start + window >= len(tokens):
            # Пояснение: Завершаем генератор после последнего содержательного окна.
            break


# Пояснение: Создаёт .uremb; encode — переданная функция получения вектора, progress — необязательный callback.
def build_index(source, output, encode, encoding='utf-8', delimiter=';', progress=None, sheet=None):
    # Пояснение: Превращаем оба пути в Path для проверки, чтения и замены файлов.
    source, output = Path(source), Path(output)
    # Пояснение: Индекс должен иметь своё расширение и не совпадать с исходным CSV.
    if output.suffix != '.uremb' or source.resolve() == output.resolve():
        # Пояснение: Отклоняем опасный или неверно названный выходной путь.
        raise ValueError('Индекс должен иметь расширение .uremb и отдельный путь от CSV.')
    # Пояснение: Открываем исходный CSV только для чтения; with гарантирует закрытие.
    with source.open('rb') as f:
        # Пояснение: Читаем на один байт больше лимита, чтобы обнаружить превышение без чтения всего огромного
        # Пояснение: файла.
        raw = f.read(MAX_BYTES + 1)
    # Пояснение: Проверяем фактически прочитанный размер.
    if len(raw) > MAX_BYTES:
        # Пояснение: Слишком большой CSV отклоняем до создания выходного индекса.
        raise ValueError('CSV больше 256 МиБ.')
    # XLSX читает тот же backend, что терминальный интерфейс: одинаковые строки и хеши.
    if source.suffix.lower() == '.xlsx':
        # Каталог scripts вычисляется относительно проекта, а не текущего каталога запуска.
        sys.path.insert(0, str(ROOT / 'scripts'))
        # Импорт не требует библиотек ONNX: backend использует только стандартный Python.
        from xlsx_io import read_workbook
        # Копия списка нужна, поскольку ниже заголовок удаляется через pop(0).
        rows = read_workbook(raw, sheet).rows
    else:
        # Для CSV сохраняем прежние правила кодировки, BOM, кавычек и разделителя.
        text = raw.decode(encoding).removeprefix('\ufeff')
        # Нулевой байт не допускается в строках C.
        if '\0' in text:
            raise ValueError('CSV содержит нулевой байт.')
        # Поля могут быть длиннее стандартного лимита csv-модуля.
        csv.field_size_limit(MAX_BYTES)
        # newline='' сохраняет переводы строк внутри описаний.
        rows = list(csv.reader(io.StringIO(text, newline=''), delimiter=delimiter, strict=True))
    # Пояснение: Пустой список означает отсутствие даже заголовка.
    if not rows:
        # Пояснение: Нельзя строить индекс без структуры таблицы.
        raise ValueError('CSV пуст.')
    # Пояснение: Удаляем и запоминаем первую запись: это заголовок, а не сайт.
    header = rows.pop(0)
    # Пояснение: Имена пяти обязательных столбцов.
    required = ['domain', 'class', 'label', 'action', 'description']
    # Пояснение: any обнаруживает хотя бы одно отсутствующее или повторяющееся обязательное имя.
    if any(header.count(name) != 1 for name in required):
        # Пояснение: Сообщаем требование к уникальным заголовкам.
        raise ValueError('Нужны уникальные domain, class, label, action, description.')
    # Пояснение: Находим реальные позиции домена и описания независимо от порядка столбцов.
    domain, description = header.index('domain'), header.index('description')
    # Пояснение: Проверяем одинаковое число полей во всех записях.
    if any(len(row) != len(header) for row in rows):
        # Пояснение: Строку с другой шириной CSV отклоняем.
        raise ValueError('Количество полей CSV не совпадает с заголовком.')
    # Пояснение: Прогнозируем размер: заголовок 16 байтов плюс хеш 8 и DIM чисел float32 по 4 байта на сайт.
    if 16 + len(rows) * (8 + 4 * DIM) > MAX_BYTES:
        # Пояснение: Индекс, который C-часть не сможет прочитать по своему лимиту, не создаём.
        raise ValueError('Индекс превысит 256 МиБ.')
    # Пояснение: Создаём каталог индекса при необходимости, разрешая уже существующий.
    output.parent.mkdir(parents=True, exist_ok=True)
    # Пояснение: Пока нет временного файла, который потребуется удалить при ошибке.
    temporary = None
    # Пояснение: Блок с finally обеспечит очистку незавершённого индекса.
    try:
        # Пояснение: Временный файл создаётся рядом с итоговым, чтобы os.replace работал в одной файловой
        # Пояснение: системе.
        with tempfile.NamedTemporaryFile(prefix=output.name + '.', suffix='.tmp', dir=output.parent, delete=False) as f:
            # Пояснение: Запоминаем имя файла; delete=False оставляет его после закрытия для последующего
            # Пояснение: rename.
            temporary = Path(f.name)
            # Пояснение: Пишем 8-байтную сигнатуру и два unsigned int32 little-endian: число сайтов и
            # Пояснение: размерность.
            f.write(b'UREMB01\n' + struct.pack('<II', len(rows), DIM))
            # Пояснение: Нумерация сайтов начинается с 1, как в C-таблице после заголовка.
            for number, row in enumerate(rows, 1):
                # Пояснение: Извлекаем описание текущего сайта.
                desc = row[description]
                # Пояснение: Для непустого описания вызываем encode; для пустого создаём нулевой вектор, не
                # Пояснение: вызывая модель.
                vector = list(encode(desc)) if desc.strip() else [0.0] * DIM
                # Пояснение: Проверяем длину и конечность всех чисел, исключая NaN и бесконечности.
                if len(vector) != DIM or any(not math.isfinite(v) for v in vector):
                    # Пояснение: Некорректный ответ модели останавливает построение.
                    raise ValueError('Модель вернула неверный вектор.')
                # Пояснение: Евклидова норма: корень из суммы квадратов координат.
                norm = math.sqrt(sum(v * v for v in vector))
                # Пояснение: Нулевой вектор допустим для пустого описания, но не для непустого текста.
                if desc.strip() and norm == 0:
                    # Пояснение: Явно сообщаем о неинформативном ответе модели.
                    raise ValueError('Модель вернула нулевой вектор для непустого описания.')
                # Пояснение: Ненулевой вектор приводим к единичной длине.
                if norm:
                    # Пояснение: Делим каждую координату на норму; направление вектора сохраняется.
                    vector = [v / norm for v in vector]
                # Пояснение: Пишем 64-битный отпечаток домена и исходного описания; <Q задаёт little-endian
                # Пояснение: uint64.
                f.write(struct.pack('<Q', fingerprint(row[domain], desc)))
                # Пояснение: Пишем 384 числа float32; *vector разворачивает список в аргументы struct.pack.
                f.write(struct.pack('<384f', *vector))
                # Пояснение: Если вызывающий код передал callback, можно сообщать ход обработки.
                if progress:
                    # Пояснение: Передаём число готовых записей и общее количество.
                    progress(number, len(rows))
            # Пояснение: Выгружаем буфер Python в ОС.
            f.flush()
            # Пояснение: Просим ОС синхронизировать содержимое временного файла.
            os.fsync(f.fileno())
        # Пояснение: После закрытия атомарно заменяем итоговый файл подготовленным индексом.
        os.replace(temporary, output)
        # Пояснение: Временное имя больше не принадлежит нам: файл уже переименован.
        temporary = None
    # Пояснение: Этот блок выполняется и при успехе, и при исключении.
    finally:
        # Пояснение: Удаление нужно только если замена ещё не состоялась.
        if temporary is not None:
            # Пояснение: Удаляем частичный индекс; missing_ok допускает его отсутствие.
            temporary.unlink(missing_ok=True)
    # Пояснение: Возвращаем число проиндексированных сайтов.
    return len(rows)


# Пояснение: Проверяет наличие и точные контрольные суммы локальных модели и токенизатора.
def verify_model(directory):
    # Пояснение: Идём по обязательным файлам; удалённый путь здесь не нужен, поэтому имя _.
    for name, (_, expected) in FILES.items():
        # Пояснение: Составляем локальный путь файла.
        path = Path(directory) / name
        # Пояснение: Проверяем, что это существующий обычный файл.
        if not path.is_file():
            # Пояснение: При отсутствии предлагаем команду установки; автоматического скачивания здесь нет.
            raise ValueError('Модель не установлена. Сначала scripts/setup-embeddings.sh')
        # Пояснение: Создаём накопитель SHA-256.
        digest = hashlib.sha256()
        # Пояснение: Читаем файл бинарно и закрываем через with.
        with path.open('rb') as f:
            # Пояснение: iter вызывает lambda до пустого блока; по 1 МиБ экономит память.
            for block in iter(lambda: f.read(1024 * 1024), b''):
                # Пояснение: Подмешиваем очередной блок в контрольную сумму.
                digest.update(block)
        # Пояснение: Сравниваем шестнадцатеричный digest с ожидаемым для закреплённой ревизии.
        if digest.hexdigest() != expected:
            # Пояснение: Изменённый или повреждённый файл не передаём runtime.
            raise ValueError(f'Контрольная сумма {name} не совпадает. Скачайте модель заново.')


# Пояснение: Явно скачивает модель: единственная ветка этого модуля, открывающая сеть.
def download_model(directory):
    # Пояснение: Импорт сетевого клиента находится внутри функции скачивания.
    import urllib.request
    # Пояснение: Приводим каталог к Path.
    directory = Path(directory)
    # Пояснение: Создаём каталог модели и недостающих родителей.
    directory.mkdir(parents=True, exist_ok=True)
    # Пояснение: Для каждого обязательного файла берём имя, URL-путь и ожидаемую сумму.
    for name, (remote, expected) in FILES.items():
        # Пояснение: Составляем конечный локальный путь.
        path = directory / name
        # Пояснение: Уже существующий файл с правильной суммой можно использовать без повторного скачивания.
        if path.is_file() and hashlib.sha256(path.read_bytes()).hexdigest() == expected:
            # Пояснение: Сообщаем о повторном использовании, сразу сбрасывая stdout.
            print(f'{name}: уже скачан и проверен', flush=True)
            # Пояснение: Переходим к следующему файлу.
            continue
        # Пояснение: URL фиксирует репозиторий, ревизию и конкретный путь файла.
        url = f'https://huggingface.co/{MODEL_ID}/resolve/{REVISION}/{remote}'
        # Пояснение: Пока нет незавершённого скачивания.
        temp = None
        # Пояснение: Блок очистки гарантирует удаление временного скачивания при сбое.
        try:
            # Пояснение: Скачиваем во временный файл того же каталога, сохраняя конечный до проверки.
            with tempfile.NamedTemporaryFile(dir=directory, suffix='.download', delete=False) as f:
                # Пояснение: Запоминаем временное имя для очистки.
                temp = Path(f.name)
                # Пояснение: Контрольную сумму считаем по мере получения байтов.
                digest = hashlib.sha256()
                # Пояснение: Открываем HTTP-запрос с тайм-аутом 60 секунд; with закроет ответ.
                with urllib.request.urlopen(url, timeout=60) as response:
                    # Пояснение: Оператор := читает очередной блок и одновременно проверяет, не закончился ли
                    # Пояснение: поток.
                    while block := response.read(1024 * 1024):
                        # Пояснение: Добавляем полученные байты в SHA-256.
                        digest.update(block)
                        # Пояснение: Записываем тот же блок во временный файл.
                        f.write(block)
                # Пояснение: До замены проверяем точную ожидаемую сумму.
                if digest.hexdigest() != expected:
                    # Пояснение: Не принимаем скачанный файл, если байты не соответствуют закреплённой версии.
                    raise ValueError(f'Неверная контрольная сумма скачанного {name}')
            # Пояснение: Только проверенный и закрытый временный файл заменяет конечный.
            os.replace(temp, path)
            # Пояснение: Сбрасываем имя, чтобы finally не удалял уже принятый файл.
            temp = None
            # Пояснение: Сообщаем о завершённом скачивании и проверке.
            print(f'{name}: скачан и проверен', flush=True)
        # Пояснение: Очистка выполняется даже при сетевой ошибке или исключении проверки.
        finally:
            # Пояснение: Непустое temp означает оставшийся незавершённый файл.
            if temp:
                # Пояснение: Удаляем его, не требуя наличия.
                temp.unlink(missing_ok=True)
    # Пояснение: Записываем JSON-метаданные: идентификатор модели, ревизию и файлы с контрольными суммами.
    (directory / 'model-info.json').write_text(json.dumps({'model': MODEL_ID, 'revision': REVISION, 'files': FILES}, indent=2))


# Пояснение: Объект Encoder хранит токенизатор и ONNX-сеанс, чтобы не загружать их для каждого сайта заново.
class Encoder:
    # Пояснение: Конструктор принимает каталог локальной модели и число вычислительных потоков.
    def __init__(self, directory=DEFAULT_MODEL, threads=4):
        # Пояснение: Сначала проверяем файлы; ни конструктор, ни verify_model ничего не скачивают.
        verify_model(directory)
        # Пояснение: NumPy нужен для числовых массивов, норм и подготовки входов модели.
        import numpy as np
        # Пояснение: ONNX Runtime выполняет вычислительный граф готовой модели.
        import onnxruntime as ort
        # Пояснение: Tokenizer читает закреплённые правила разбивки текста.
        from tokenizers import Tokenizer
        # Пояснение: Сохраняем ссылку на NumPy в экземпляре для метода __call__.
        self.np = np
        # Пояснение: Загружаем токенизатор из локального JSON.
        self.tokenizer = Tokenizer.from_file(str(Path(directory) / 'tokenizer.json'))
        # Пояснение: Отключаем автоматическое обрезание, чтобы длинный хвост текста обрабатывался окнами.
        self.tokenizer.no_truncation()
        # Пояснение: Отключаем padding: каждое окно обрабатывается отдельно без добивки до общей длины.
        self.tokenizer.no_padding()
        # Пояснение: Создаём настройки ONNX-сеанса.
        options = ort.SessionOptions()
        # Пояснение: Задаём число потоков внутри вычислительных операторов модели.
        options.intra_op_num_threads = threads
        # Пояснение: Для параллельного исполнения независимых операторов оставляем один поток.
        options.inter_op_num_threads = 1
        # Пояснение: Загружаем локальный ONNX и явно выбираем CPU-провайдер.
        self.session = ort.InferenceSession(str(Path(directory) / 'model.onnx'), sess_options=options, providers=['CPUExecutionProvider'])
        # Пояснение: Запоминаем имена входов, реально требуемых именно этим графом.
        self.inputs = {entry.name for entry in self.session.get_inputs()}
        # E5 recommends query: on both sides for symmetric similarity tasks.
        # Пояснение: Заранее токенизируем префикс query: для симметричного сравнения описаний без автоматических
        # Пояснение: спецтокенов.
        self.prefix = self.tokenizer.encode('query: ', add_special_tokens=False).ids
        # Пояснение: Находим идентификатор токена начала последовательности.
        self.cls = self.tokenizer.token_to_id('<s>')
        # Пояснение: Находим идентификатор токена конца последовательности.
        self.sep = self.tokenizer.token_to_id('</s>')
        # Пояснение: Оба спецтокена должны существовать в выбранном токенизаторе.
        if self.cls is None or self.sep is None:
            # Пояснение: Несовместимый токенизатор отклоняем до вычислений.
            raise ValueError('Токенизатор не содержит специальные токены E5.')

    # Пояснение: Делает экземпляр вызываемым: encoder(text) вернёт список из DIM чисел.
    def __call__(self, text):
        # Пояснение: Короткое локальное имя NumPy из сохранённого атрибута.
        np = self.np
        # Only whitespace normalization: never summarize or discard the tail.
        # Пояснение: Нормализуем только пробелы и токенизируем весь текст; смысловое сокращение и обрезание не
        # Пояснение: делаем.
        tokens = self.tokenizer.encode(' '.join(text.split()), add_special_tokens=False).ids
        # Пояснение: Создаём нулевой аккумулятор 384 координат float64 для суммы векторов окон.
        total = np.zeros(DIM, dtype=np.float64)
        # Пояснение: Перебираем все окна, сохраняя конец длинного описания.
        for window in chunks(tokens):
            # Пояснение: Собираем двумерный int64-массив формы [1, длина]: начало, префикс, окно, конец.
            ids = np.asarray([[self.cls, *self.prefix, *window, self.sep]], dtype=np.int64)
            # Пояснение: Маска из единиц показывает, что все переданные токены настоящие, а не padding.
            mask = np.ones_like(ids)
            # Пояснение: Готовим входы: ID токенов, attention mask и нулевые ID сегментов.
            feeds = {'input_ids': ids, 'attention_mask': mask, 'token_type_ids': np.zeros_like(ids)}
            # Пояснение: Запускаем граф; передаём только те подготовленные входы, которые есть в self.inputs.
            outputs = self.session.run(None, {k: v for k, v in feeds.items() if k in self.inputs})
            # Пояснение: Первый выход содержит скрытые представления токенов.
            hidden = outputs[0]
            # Пояснение: Ожидаем форму [batch, tokens, 384]; неправильный выход нельзя усреднять как нужный
            # Пояснение: вектор.
            if hidden.ndim != 3 or hidden.shape[2] != DIM:
                # Пояснение: Неожиданную форму считаем ошибкой несовместимости модели.
                raise ValueError('Неожиданный выход ONNX-модели.')
            # Пояснение: Для batch 0 усредняем по токенам окна, получая один 384-мерный вектор.
            vector = hidden[0].mean(axis=0)
            # Пояснение: Вычисляем его евклидову норму.
            norm = np.linalg.norm(vector)
            # Пояснение: Норма должна быть конечной и ненулевой.
            if not np.isfinite(norm) or norm == 0:
                # Пояснение: Некорректный вектор окна не добавляем в индекс.
                raise ValueError('Неверный результат модели.')
            # Пояснение: Нормализуем каждое окно и прибавляем с равным весом к общей сумме.
            total += vector / norm
        # Пояснение: Вычисляем длину суммы окон.
        norm = np.linalg.norm(total)
        # Пояснение: Нормализуем итог, если он ненулевой, и превращаем NumPy-массив в обычный Python-список.
        return (total / norm if norm else total).tolist()


# Пояснение: Точка входа командной строки Python-компонента.
def main():
    # Пояснение: Создаём парсер аргументов с текстом встроенной справки.
    parser = argparse.ArgumentParser(description='Локальные эмбеддинги E5 для URL Review')
    # Пояснение: Разрешаем явно указать каталог локальной модели.
    parser.add_argument('--model-dir', type=Path, default=DEFAULT_MODEL)
    # Пояснение: Требуем подкоманду; её имя попадёт в args.command.
    sub = parser.add_subparsers(dest='command', required=True)
    # Пояснение: Регистрируем download; сеть запускается только через эту подкоманду.
    sub.add_parser('download', help='Скачать модель: единственная команда с доступом в сеть')
    # Пояснение: Регистрируем build для создания индекса.
    build = sub.add_parser('build', help='Создать индекс локально, без сети')
    # Пояснение: Первый обязательный путь build — исходный CSV.
    build.add_argument('input', type=Path)
    # Пояснение: Второй обязательный путь build — выходной .uremb.
    build.add_argument('output', type=Path)
    # Для XLSX разрешаем явно назвать лист, совпадающий с --sheet приложения.
    build.add_argument('--sheet')
    # Пояснение: Допустимые кодировки, по умолчанию UTF-8.
    build.add_argument('--encoding', choices=['utf-8', 'windows-1251'], default='utf-8')
    # Пояснение: Допустимые разделители, по умолчанию точка с запятой.
    build.add_argument('--delimiter', choices=[';', ',', 'tab'], default=';')
    # Пояснение: Число потоков — целое от 1 до 16 включительно; range не включает 17.
    build.add_argument('--threads', type=int, choices=range(1, 17), default=4)
    # Пояснение: Регистрируем smoke — короткую проверку настоящей локальной модели.
    sub.add_parser('smoke', help='Проверить настоящую модель на вымышленных русских описаниях')
    # Пояснение: Разбираем аргументы; argparse сам обрабатывает --help и синтаксические ошибки.
    args = parser.parse_args()
    # Пояснение: Обрабатываем ожидаемые ошибки без длинной трассировки.
    try:
        # Пояснение: Отдельная ветка только для явно запрошенного скачивания.
        if args.command == 'download':
            # Пояснение: Вызываем скачивание в выбранный каталог.
            download_model(args.model_dir)
            # Пояснение: Завершаем команду, не загружая модель для вычислений.
            return
        # Пояснение: Монотонные часы подходят для измерения длительности, независимо от перевода системных
        # Пояснение: часов.
        start = time.monotonic()
        # Пояснение: Создаём encoder; у smoke нет --threads, поэтому getattr даёт значение 4.
        encoder = Encoder(args.model_dir, getattr(args, 'threads', 4))
        # Пояснение: Ветка проверки настоящей модели на маленьких вымышленных примерах.
        if args.command == 'smoke':
            # Пояснение: Первый текст — магазин инструментов.
            texts = ['Интернет-магазин ручных инструментов, дрелей и оборудования для мастерской.',
                     # Пояснение: Второй текст близок по смыслу первому.
                     'Продажа электроинструментов: дрели, шуруповёрты, товары для ремонта.',
                     # Пояснение: Третий текст — музыкальная школа, контрольный другой смысл.
                     'Музыкальная школа: уроки фортепиано, вокал и обучение игре на скрипке.']
            # Пояснение: Получаем по вектору для каждого из трёх текстов.
            vectors = [encoder(text) for text in texts]
            # Пояснение: Для единичных векторов скалярное произведение равно косинусному сходству двух
            # Пояснение: магазинов.
            similar = sum(a*b for a,b in zip(vectors[0],vectors[1]))
            # Пояснение: Аналогично сравниваем магазин с музыкальной школой.
            different = sum(a*b for a,b in zip(vectors[0],vectors[2]))
            # Пояснение: Печатаем обе меры сходства с четырьмя знаками после запятой.
            print(f'Магазин ↔ магазин: {similar:.4f}; магазин ↔ музыкальная школа: {different:.4f}')
            # Пояснение: Ожидаем, что близкие тексты окажутся похожее, чем контрольная другая тема.
            if similar <= different:
                # Пояснение: Если это не так, smoke завершится ошибкой.
                raise ValueError('Проверка смыслового сходства не пройдена.')
        # Пояснение: Остальная разрешённая команда здесь — build.
        else:
            # Пояснение: Сообщаем о локальной обработке и возможности отмены.
            print('Локальная обработка. Исходная таблица не изменяется. Ctrl+C — отмена.', flush=True)
            # Пояснение: Вложенная функция обратного вызова для прогресса; использует start из внешней области.
            def progress(done, total):
                # Пояснение: Печатаем первую, каждую десятую и последнюю запись.
                if done == 1 or done % 10 == 0 or done == total:
                    # Пояснение: Показываем количество готовых и длительность с десятыми долями секунды.
                    print(f'{done}/{total}: {time.monotonic()-start:.1f} с', flush=True)
            # Пояснение: Строим индекс с выбранными настройками; слово tab переводим в реальный байт табуляции.
            count = build_index(args.input, args.output, encoder, args.encoding, '\t' if args.delimiter == 'tab' else args.delimiter, progress, args.sheet)
            # Пояснение: Сообщаем число сайтов и путь итогового индекса.
            print(f'Готово: {count} записей → {args.output}')
        # Пояснение: Печатаем общую длительность, включая загрузку локальной модели.
        print(f'Время с загрузкой модели: {time.monotonic()-start:.2f} с')
    # Пояснение: Ожидаемые ошибки файлов, данных, CSV, зависимостей и runtime обрабатываем вместе.
    except (OSError, ValueError, csv.Error, ImportError, RuntimeError) as exc:
        # Пояснение: Краткое сообщение направляем в stderr.
        print(f'Ошибка: {exc}', file=sys.stderr)
        # Пояснение: Возвращаем ОС код ошибки 1.
        sys.exit(1)
    # Пояснение: Ctrl+C превращается в KeyboardInterrupt.
    except KeyboardInterrupt:
        # Пояснение: Сообщаем об отмене; build_index очистит временный индекс через finally.
        print('\nОтменено; исходная таблица не изменена.', file=sys.stderr)
        # Пояснение: Стандартный код прерывания процесса — 130.
        sys.exit(130)


# Пояснение: При прямом запуске вызываем CLI; при импорте в тестах main не выполняется.
if __name__ == '__main__':
    # Пояснение: Запускаем разбор аргументов и выбранную подкоманду.
    main()
