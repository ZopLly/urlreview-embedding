// Пояснение: Ищет следующую непроверенную и не отложенную запись по кругу после after.
static size_t pending(const UI *ui,size_t after) {
    // Пояснение: Берём таблицу для перебора.
    const Table *t=&ui->store->table;
    // Пояснение: Если кроме заголовка ничего нет, возвращаем 0 — конец прохода.
    if(t->count<=1) return 0;
    // Пояснение: Обходим каждую запись данных ровно один раз.
    for(size_t step=1;step<t->count;step++) {
        // Пояснение: Модуль замыкает обход по кругу; +1 исключает заголовок, after=0 начинает с первой записи.
        size_t row=((after?after-1:t->count-2)+step)%(t->count-1)+1;
        // Пояснение: Возвращаем первый сайт без флага deferred и с пустым action.
        if(!ui->deferred[row] && !*cell(t,row,ACTION)) return row;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Подходящих записей нет: показываем итог прохода.
    return 0;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Открывает запись, сбрасывает прокрутку и обновляет историю переходов.
static void visit(UI *ui,size_t row) {
    // Пояснение: Устанавливаем номер, прокрутку 0 и очищаем кэш прежнего описания.
    ui->row=row;ui->scroll=0;lines_free(&ui->description);
    // Пояснение: row=0 означает итог, его не добавляем в историю сайтов.
    if(!row) return;
    // Пояснение: Повторный визит к текущему элементу истории не дублирует запись.
    if(ui->history_count && ui->history[ui->history_pos]==row) return;
    // Пояснение: После возврата назад новый переход отсекает будущую ветку истории.
    if(ui->history_count) ui->history_count=ui->history_pos+1;
    // Пояснение: Расширяем массив истории на один номер.
    ui->history=mem_resize(ui->history,(ui->history_count+1)*sizeof *ui->history);
    // Пояснение: Добавляем запись и перемещаем позицию истории к её последнему элементу.
    ui->history[ui->history_count++]=row;ui->history_pos=ui->history_count-1;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Возвращается к предыдущему посещённому сайту текущего сеанса.
static void back(UI *ui) {
    // Пояснение: Без истории выводим сообщение и остаёмся на текущем экране.
    if(!ui->history_count) {snprintf(ui->message,sizeof ui->message,"В этом сеансе пока нет просмотренных записей.");return;}
    // Пояснение: Если открыт сайт и есть предшественник, сдвигаем позицию назад; с итогового экрана берём
    // Пояснение: последний визит.
    if(ui->row && ui->history_pos) ui->history_pos--;
    // Пояснение: Восстанавливаем номер из истории, сбрасываем прокрутку и переносы.
    ui->row=ui->history[ui->history_pos];ui->scroll=0;lines_free(&ui->description);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
