// Пояснение: Формирует отображаемые итоговые категории похожей записи по её action/class/label.
static char *final_categories(const Table *t,size_t row) {
    // Пояснение: Берём исходную категорию и ручной label как заимствованные строки таблицы.
    const char *category=cell(t,row,CLASS),*label=cell(t,row,LABEL);
    // Пояснение: Только OK подтверждает исходный class.
    bool ok=!strcmp(cell(t,row,ACTION),"OK");
    // Пояснение: Выделяем обнулённый результат с запасом на пробелы и пояснение пустого итога.
    char *result=mem_alloc(strlen(category)+2*strlen(label)+64);
    // Пояснение: При OK исходный class включается в итог; при ERROR и NOT_DESC — нет.
    if(ok)strcpy(result,category);
    // Пояснение: Копируем label, потому что strtok_r меняет разделители внутри строки; save хранит состояние
    // Пояснение: разбивки.
    char *copy=str_copy(label),*save=NULL;
    // Пояснение: Перебираем части label через запятую; NULL продолжает прежнюю разбивку.
    for(char *part=strtok_r(copy,",",&save);part;part=strtok_r(NULL,",",&save)) {
        // Пояснение: Пропускаем начальные пробельные байты; unsigned char нужен для корректного isspace.
        while(isspace((unsigned char)*part))part++;
        // Пояснение: Обрезаем пробелы справа, заменяя их нулём.
        size_t n=strlen(part);while(n&&isspace((unsigned char)part[n-1]))part[--n]=0;
        // Пояснение: Пропускаем пустую часть и повтор исходного class при OK.
        if(!n||(ok&&!strcmp(part,category)))continue;
        // Пояснение: Между уже имеющимися категориями вставляем запятую с пробелом.
        if(*result)strcat(result,", ");
        // Пояснение: Добавляем очередной код категории к результату.
        strcat(result,part);
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Временная изменяемая копия label больше не нужна.
    free(copy);
    // Пояснение: Если подтверждённых кодов нет, показываем понятный текст.
    if(!*result)strcpy(result,"не определены");
    // Пояснение: Возвращаем выделенную строку; вызывающий код освободит её.
    return result;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Показывает полное описание и прежнюю ручную разметку выбранного похожего сайта.
static void similar_detail(UI *ui,size_t row,float score) {
    // Пояснение: Короткий указатель на текущую таблицу.
    const Table *t=&ui->store->table;
    // Пояснение: Берём домен, action и class нужной записи; объявление продолжается ниже.
    const char *domain=cell(t,row,DOMAIN),*action=cell(t,row,ACTION),*category=cell(t,row,CLASS),
        // Пояснение: Дополняем объявление указателями на label и описание.
        *label=cell(t,row,LABEL),*description=cell(t,row,DESCRIPTION);
    // Пояснение: Строим отображаемый итог по правилам действия.
    char *final=final_categories(t,row);
    // Пояснение: Суммируем длины вставляемых значений плюс запас для подписей и чисел.
    size_t n=strlen(domain)+strlen(action)+strlen(category)+strlen(label)+strlen(final)+strlen(description)+900;
    // Пояснение: Выделяем тело окна подробностей.
    char *body=mem_alloc(n);
    // Пояснение: Начинаем шаблон: номер сайта, номер CSV-записи с заголовком, домен и сходство.
    snprintf(body,n,"Запись №%zu | Строка таблицы: %zu (с заголовком)\n%s\nСходство: %.3f — не вероятность правильной категории.\n\n"
        // Пояснение: Соседний литерал продолжает шаблон принятой разметки и полного описания.
        "Принятая разметка:\nРешение: %s\nИсходный class: %s\nlabel: %s\nИтоговые категории: %s\n\n%s\nОписание:\n%s",
        // Пояснение: Передаём значения по порядку %; source_rows даёт номер Excel, для CSV row+1 учитывает заголовок, пустой label получает подпись.
        row,t->source_rows?t->source_rows[row]:row+1,domain,(double)score,action,category,*label?label:"(пусто)",final,
        // Пояснение: Для NOT_DESC добавляем пояснение, почему этот пример не подтверждает категорию.
        !strcmp(action,"NOT_DESC")?"NOT_DESC: описание недостаточно; пример не подтверждает категорию.\n":"",
        // Пояснение: Последний аргумент шаблона — полное описание сайта.
        description);
    // Пояснение: Показываем текст, затем освобождаем тело и строку итоговых категорий.
    viewer("Похожая запись",body);free(body);free(final);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
