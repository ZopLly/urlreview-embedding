// Пояснение: Вход в интерактивный сеанс; компоненты уже созданы в main и освобождаются там.
int ui_run(Store *store,const Guide *guide,const Embedding *index) {
    // Пояснение: Сбрасываем флаг прежнего прерывания.
    stopped=0;
    // Пояснение: Устанавливаем обработчики SIGINT/SIGTERM и сохраняем прежние указатели функций.
    void (*old_int)(int)=signal(SIGINT,interrupted),(*old_term)(int)=signal(SIGTERM,interrupted);
    // Пояснение: Инициализируем ncurses; при невозможности открыть экран завершаем с ошибкой.
    if(!initscr()) {fputs("Не удалось открыть терминальный интерфейс.\n",stderr);return 1;}
    // Пояснение: Клавиши без Enter, без эха, распознавание стрелок, скрытый курсор, опрос 100 мс и Escape delay
    // Пояснение: 25 мс.
    cbreak();noecho();keypad(stdscr,TRUE);curs_set(0);timeout(100);set_escdelay(25);
    // Пояснение: Включаем сообщения левой кнопки и обоих направлений колеса.
    mousemask(BUTTON1_PRESSED|BUTTON4_PRESSED|BUTTON5_PRESSED,NULL);
    // Пояснение: Если цвета поддерживаются, задаём пару 1: cyan на стандартном фоне.
    if(has_colors()) {start_color();use_default_colors();init_pair(1,COLOR_CYAN,-1);}
    // Пояснение: Создаём пустой UI, подключаем заимствованные компоненты и выделяем обнулённые флаги
    // Пояснение: отложенных.
    UI ui={0};ui.store=store;ui.guide=guide;ui.index=index;ui.deferred=mem_alloc(store->table.count*sizeof *ui.deferred);
    // Пояснение: Открываем первую доступную непроверенную запись через общий механизм visit.
    visit(&ui,pending(&ui,0));
    // Пояснение: Обычный флаг выхода по Q отдельно от сигналов.
    bool quit=false;
    // Пояснение: Основной цикл событий до команды выхода или сигнала.
    while(!quit && !stopped) {
        // Пояснение: Проверяем дочерние процессы браузера без блокировки ввода.
        poll_browsers(&ui);
        // Пояснение: Рисуем карточку только в достаточно большом окне.
        if(!small_screen()) render(&ui);
        // Пояснение: Тайм-аут getch без события вызывает новую итерацию, позволяя опрашивать процессы и
        // Пояснение: сигналы.
        int key=read_key();if(key==ERR) continue;
        // Пояснение: Q прекращает основной цикл без черновика.
        if(key=='q'||key=='Q') {quit=true;continue;}
        // Пояснение: В маленьком окне дальнейшие команды не применяем к невидимой карточке.
        if(small_screen()) continue;
        // Пояснение: H/F1 открывает справку и возвращается в цикл.
        if(key=='h'||key=='H'||key==KEY_F(1)) {general_help();continue;}
        // Пояснение: B восстанавливает предыдущий визит и возвращается в цикл.
        if(key=='b'||key=='B') {back(&ui);continue;}
        // Пояснение: На итоговом экране действует отдельный набор команд.
        if(!ui.row) {
            // Пояснение: R очищает отложенные флаги и начинает новый поиск непроверенных.
            if(key=='r'||key=='R') {memset(ui.deferred,0,store->table.count*sizeof *ui.deferred);visit(&ui,pending(&ui,0));}
            // Пояснение: V позволяет открыть первую запись данных, даже если она уже проверена.
            if((key=='v'||key=='V') && store->table.count>1) visit(&ui,1);
            // Пояснение: Не выполняем команды карточки, когда самой текущей записи нет.
            continue;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: P открывает похожие записи.
        if(key=='p'||key=='P') {similar(&ui);continue;}
        // Пояснение: O или левый клик по домену вызывает открытие сайта.
        if(key=='o'||key=='O'||(key==KEY_MOUSE && domain_clicked(&ui))) {open_site(&ui);continue;}
        // Пояснение: Цифры 1–3 выбирают вид ручного решения.
        if(key>='1'&&key<='3') {
            // Пояснение: Массив сопоставляет клавиши кодам действий.
            static const char *actions[]={"OK","ERROR","NOT_DESC"};
            // Пояснение: Вычитаем символ '1', получая индекс 0–2, и запускаем выбор категорий.
            int result=choose_categories(&ui,actions[key-'1']);
            // Пояснение: Код 2 из вложенных экранов означает запрос выйти из всего приложения.
            if(result==2) quit=true;
            // Пояснение: После успешного сохранения снимаем deferred и открываем следующую доступную запись.
            else if(result==1) {ui.deferred[ui.row]=false;visit(&ui,pending(&ui,ui.row));}
        // Пояснение: S откладывает сайт только в памяти и переходит дальше без записи CSV.
        } else if(key=='s'||key=='S') {ui.deferred[ui.row]=true;visit(&ui,pending(&ui,ui.row));}
        // Пояснение: Иные клавиши передаём обработчику прокрутки описания.
        else scroll_key(key,&ui.scroll,ui.description.count,LINES-12);
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Освобождаем состояние UI, отключаем мышь и возвращаем терминал в обычный режим через endwin.
    lines_free(&ui.description);free(ui.history);free(ui.deferred);mousemask(0,NULL);endwin();
    // Пояснение: Восстанавливаем обработчики сигналов; при прерывании возвращаем 130, иначе 0.
    signal(SIGINT,old_int);signal(SIGTERM,old_term);return stopped?130:0;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
