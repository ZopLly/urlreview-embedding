// Пояснение: Превращает многобайтовый текст текущей локали в выделенный массив широких символов.
static wchar_t *wide_text(const char *s) {
    // Пояснение: Число байтов UTF-8 — верхняя граница числа символов; выделяем ещё место под ноль.
    size_t n=strlen(s); wchar_t *w=mem_alloc((n+1)*sizeof *w);
    // Пояснение: Обнуляем состояние декодера; i считает широкие символы, pos — байты входа.
    mbstate_t state={0};size_t i=0,pos=0;
    // Пояснение: Читаем, пока не достигнут конец входных байтов.
    while(pos<n) {
        // Пояснение: mbrtowc декодирует один символ и возвращает число использованных байтов.
        wchar_t ch;size_t k=mbrtowc(&ch,s+pos,n-pos,&state);
        // Пояснение: Неверную/неполную последовательность показываем символом замены, пропускаем байт и
        // Пояснение: сбрасываем декодер.
        if(k==(size_t)-1 || k==(size_t)-2) { ch=L'�';k=1;memset(&state,0,sizeof state); }
        // Пояснение: Нулевой символ означает конец строки.
        if(!k) break;
        // Пояснение: Записываем символ и сдвигаем обе позиции в их единицах измерения.
        w[i++]=ch;pos+=k;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Добавляем широкий ноль и возвращаем выделенную строку.
    w[i]=0;return w;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Выводит одну строку в координатах y,x, ограничивая ширину экранными ячейками.
static void text(int y,int x,const char *s,int width) {
    // Пояснение: За пределами терминала или при неположительной ширине рисовать нельзя.
    if(y<0 || y>=LINES || x<0 || x>=COLS || width<=0) return;
    // Пояснение: Дополнительно ограничиваем ширину правой границей экрана.
    if(width>COLS-x) width=COLS-x;
    // Пояснение: Декодируем UTF-8; cells — занятые экранные колонки, n — число символов.
    wchar_t *w=wide_text(s);int cells=0;size_t n=0;
    // Пояснение: Проверяем символы до завершающего нуля.
    while(w[n]) {
        // Пояснение: wcwidth даёт ширину символа в терминальных колонках, что важно для кириллицы и широких
        // Пояснение: знаков.
        int size=wcwidth(w[n]);
        // Пояснение: Непечатаемый символ заменяем пробелом шириной 1.
        if(size<0) { w[n]=L' ';size=1; }
        // Пояснение: Если следующий символ не помещается, заканчиваем строку без его частичного вывода.
        if(cells+size>width) break;
        // Пояснение: Учитываем ширину принятого символа и увеличиваем число выводимых символов.
        cells+=size;n++;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: ncurses выводит n широких символов; временную декодированную строку освобождаем.
    mvaddnwstr(y,x,w,(int)n);free(w);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Освобождает кэш перенесённого текста.
static void lines_free(Lines *l) {
    // Пояснение: Сначала освобождаем каждую широкую строку.
    for(size_t i=0;i<l->count;i++) free(l->items[i]);
    // Пояснение: Затем массив указателей; обнуление сбрасывает count и width.
    free(l->items);memset(l,0,sizeof *l);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Добавляет независимую копию n широких символов как новую экранную строку.
static void line_add(Lines *l,const wchar_t *w,size_t n) {
    // Пояснение: Расширяем массив указателей на один элемент.
    l->items=mem_resize(l->items,(l->count+1)*sizeof *l->items);
    // Пояснение: Выделяем обнулённую память n+1, поэтому после memcpy уже есть завершающий ноль.
    wchar_t *copy=mem_alloc((n+1)*sizeof *copy);memcpy(copy,w,n*sizeof *copy);
    // Пояснение: Передаём владение строкой кэшу и увеличиваем число строк.
    l->items[l->count++]=copy;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Переносит UTF-8 текст на экранные строки не шире width; перенос идёт по символам.
static void lines_make(Lines *l,const char *s,int width) {
    // Пояснение: Удаляем старый кэш, гарантируем ширину хотя бы 1 и запоминаем её.
    lines_free(l);if(width<1) width=1;l->width=width;
    // Пояснение: Декодируем текст и выделяем рабочую строку с запасом по числу исходных байтов.
    wchar_t *w=wide_text(s), *line=mem_alloc((strlen(s)+2)*sizeof *line);
    // Пояснение: len считает символы текущей строки, cells — её экранную ширину.
    size_t len=0;int cells=0;
    // Пояснение: Перебираем широкие символы текста.
    for(size_t i=0;w[i];i++) {
        // Пояснение: CR игнорируем при отображении, чтобы пара CRLF не давала лишний перенос.
        wchar_t ch=w[i];if(ch==L'\r') continue;
        // Пояснение: LF явно завершает строку; сохраняем даже пустую строку и сбрасываем её счётчики.
        if(ch==L'\n') {line_add(l,line,len);len=0;cells=0;continue;}
        // Пояснение: Определяем экранную ширину символа.
        int size=wcwidth(ch);
        // Пояснение: Непечатаемые знаки и табуляцию отображаем одним пробелом.
        if(size<0 || ch==L'\t') {ch=L' ';size=1;}
        // Пояснение: Символ шире всей строки заменяем вопросительным знаком.
        if(size>width) {ch=L'?';size=1;}
        // Пояснение: Перед превышением ширины сохраняем текущую строку и начинаем новую.
        if(cells+size>width && len) {line_add(l,line,len);len=0;cells=0;}
        // Пояснение: Добавляем символ и увеличиваем её экранную ширину.
        line[len++]=ch;cells+=size;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Сохраняем непустой хвост; пустой текст всё равно получает одну экранную строку.
    if(len || !l->count) line_add(l,line,len);
    // Пояснение: Освобождаем декодированный текст и рабочий буфер; кэш уже содержит копии.
    free(w);free(line);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Рисует видимую часть перенесённых строк начиная со смещения scroll.
static void draw_lines(const Lines *l,int top,int height,size_t scroll) {
    // Пояснение: Ограничиваемся высотой и количеством строк; -1 просит ncurses вывести широкую строку целиком.
    for(int i=0;i<height && scroll+(size_t)i<l->count;i++) mvaddnwstr(top+i,2,l->items[scroll+(size_t)i],-1);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
