// Пояснение: Строит абсолютный путь рабочей копии, даже если сам файл ещё не создан.
static char *canonical_output(const char *path, char err[ERR_SIZE]) {
    // Пояснение: Копируем путь для изменения и ищем последний слеш, отделяющий имя файла.
    char *copy = str_copy(path), *slash = strrchr(copy,'/');
    // Пояснение: Выбираем часть после слеша либо весь путь, если каталога нет.
    const char *name = slash ? slash+1 : copy;
    // Пояснение: Отклоняем пустое имя, точку и две точки: нужен файл, а не каталог.
    if (!*name || !strcmp(name,".") || !strcmp(name,"..")) { snprintf(err,ERR_SIZE,"Нужно имя файла рабочей копии."); free(copy); return NULL; }
    // Пояснение: Сохраняем имя отдельной строкой перед изменением пути каталога.
    char *base = str_copy(name);
    // Пояснение: Отсекаем имя от каталога; отдельно учитываем корневой каталог /.
    if (slash) { if (slash==copy) slash[1]=0; else *slash=0; }
    // Пояснение: realpath разрешает существующий каталог и ссылки; при отсутствии каталога в пути берём
    // Пояснение: текущий.
    char *dir = realpath(slash ? copy : ".", NULL);
    // Пояснение: При недоступном каталоге сообщаем причину и освобождаем обе временные строки.
    if (!dir) { snprintf(err,ERR_SIZE,"Каталог рабочей копии недоступен: %s",strerror(errno)); free(base); free(copy); return NULL; }
    // Пояснение: Места хватает на каталог, слеш, имя и завершающий ноль.
    char *result = mem_alloc(strlen(dir)+strlen(base)+2);
    // Пояснение: Собираем абсолютный путь, освобождаем части и передаём результат вызывающему коду.
    sprintf(result,"%s/%s",dir,base); free(dir); free(base); free(copy); return result;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Проверяет, что выходной путь не указывает на исходник или неподходящий объект.
static bool protected_path(Store *s, char err[ERR_SIZE]) {
    // Пояснение: Здесь будут метаданные объекта по выходному пути.
    struct stat st;
    // Пояснение: Совпадение нормализованных путей запрещает запись поверх исходника.
    if (!strcmp(s->input,s->output)) { snprintf(err,ERR_SIZE,"Исходник и рабочая копия должны быть разными файлами."); return false; }
    // Пояснение: lstat проверяет саму ссылку, а не объект за ней; ноль означает существование.
    if (lstat(s->output,&st)==0) {
        // Пояснение: Отклоняем не обычный файл и тот же inode на том же устройстве, включая жёсткую ссылку.
        if (!S_ISREG(st.st_mode) || (st.st_dev==s->input_dev && st.st_ino==s->input_ino)) {
            // Пояснение: Сообщаем, что рабочая копия должна быть самостоятельным файлом.
            snprintf(err,ERR_SIZE,"Рабочая копия должна быть отдельным обычным файлом, не ссылкой на исходник."); return false;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
    // Пояснение: ENOENT допускает новый файл; прочие ошибки проверки пути останавливают запись.
    } else if (errno!=ENOENT) { snprintf(err,ERR_SIZE,"Не удалось проверить рабочую копию: %s",strerror(errno)); return false; }
    // Пояснение: Выходной путь прошёл текущую проверку.
    return true;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Сравнивает файл на диске с последним снимком байтов, известным этому сеансу.
static bool unchanged(Store *s, char err[ERR_SIZE]) {
    // Пояснение: Сначала повторяем защиту исходника и проверку типа выходного объекта.
    if (!protected_path(s,err)) return false;
    // Пояснение: Без снимка ожидаем, что рабочая копия ещё не существует.
    if (!s->snapshot) {
        // Пояснение: Структура для проверки появления файла.
        struct stat st;
        // Пояснение: Если файл появился или проверка завершилась иной ошибкой, не перезаписываем чужие данные.
        if (lstat(s->output,&st)==0 || errno!=ENOENT) { snprintf(err,ERR_SIZE,"Рабочая копия появилась извне. Перезапустите приложение."); return false; }
        // Пояснение: Отсутствие файла соответствует ожидаемому состоянию до первого сохранения.
        return true;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Читаем рабочую копию заново; ошибка чтения останавливает сохранение.
    size_t n; char *data=read_bytes(s->output,&n,err); if (!data) return false;
    // Пояснение: Сравниваем длины и все байты со снимком, затем освобождаем свежепрочитанный текст.
    bool ok=n==s->snapshot_len && !memcmp(data,s->snapshot,n); free(data);
    // Пояснение: При любом отличии предупреждаем о внешнем редактировании.
    if (!ok) snprintf(err,ERR_SIZE,"Рабочая копия изменена другой программой. Запись отменена; перезапустите приложение.");
    // Пояснение: Возвращаем результат побайтового сравнения.
    return ok;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Записывает подготовленные байты через временный файл и rename в том же каталоге.
static SaveResult atomic_write(Store *s, const char *data, size_t n, char err[ERR_SIZE]) {
    // Пояснение: До создания временного файла убеждаемся, что рабочая копия не изменилась.
    if (!unchanged(s,err)) return SAVE_FAILED;
    // Пояснение: Выделяем из абсолютного пути имя каталога.
    char *dir=str_copy(s->output), *slash=strrchr(dir,'/'); *slash=0;
    // Пояснение: Открываем каталог для последующего fsync; CLOEXEC закрывает дескриптор при запуске другой
    // Пояснение: программы.
    int dirfd=open(*dir?dir:"/",O_RDONLY|O_DIRECTORY|O_CLOEXEC);free(dir);
    // Пояснение: Без дескриптора каталога нельзя выполнить весь протокол сохранения.
    if(dirfd<0) {snprintf(err,ERR_SIZE,"Не удалось открыть каталог для синхронизации: %s",strerror(errno));return SAVE_FAILED;}
    // Пояснение: Создаём шаблон имени временного файла рядом с рабочей копией.
    char *temp=mem_alloc(strlen(s->output)+16); sprintf(temp,"%s.tmp.XXXXXX",s->output);
    // Пояснение: mkstemp атомарно создаёт уникальный файл с правами владельца и заменяет XXXXXX в имени.
    int fd=mkstemp(temp);
    // Пояснение: При неудаче создания очищаем имя и дескриптор каталога.
    if (fd<0) { snprintf(err,ERR_SIZE,"Не удалось создать временный файл: %s",strerror(errno)); free(temp);close(dirfd); return SAVE_FAILED; }
    // Пояснение: pos — число записанных байтов; ok хранит успех последовательности операций.
    size_t pos=0; bool ok=true;
    // Пояснение: Продолжаем, пока не записаны все n байтов: write может записать только часть.
    while (pos<n) {
        // Пояснение: Пишем ещё не записанный хвост из data.
        ssize_t k=write(fd,data+pos,n-pos);
        // Пояснение: Системный вызов, прерванный сигналом, повторяем.
        if (k<0 && errno==EINTR) continue;
        // Пояснение: Ошибка или нулевая запись прерывает цикл как неудачу.
        if (k<=0) { ok=false; break; }
        // Пояснение: Продвигаем позицию на фактически записанное число байтов.
        pos+=(size_t)k;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Просим ОС синхронизировать содержимое временного файла перед заменой рабочей копии.
    if (ok && fsync(fd)!=0) ok=false;
    // Пояснение: Учитываем ошибку закрытия файла тоже.
    if (close(fd)!=0) ok=false;
    // Пояснение: Сообщаем об ошибке записи системным текстом errno.
    if (!ok) snprintf(err,ERR_SIZE,"Ошибка записи: %s",strerror(errno));
    // Пояснение: Снова сравниваем рабочую копию со снимком перед её заменой.
    if (ok) ok=unchanged(s,err);
    // Пояснение: rename атомарно меняет имя файла внутри файловой системы; ошибка оставляет ok=false.
    if (ok && rename(temp,s->output)!=0) { snprintf(err,ERR_SIZE,"Не удалось заменить рабочую копию: %s",strerror(errno)); ok=false; }
    // Пояснение: Пока считаем замену либо успешной, либо не состоявшейся.
    SaveResult result=ok?SAVE_OK:SAVE_FAILED;
    // Пояснение: Неудачный временный файл удаляем; прежняя рабочая копия остаётся.
    if (!ok) unlink(temp);
    // Пояснение: После успешного rename обновляем снимок и проверяем синхронизацию каталога.
    else {
        // Пояснение: Запоминаем новые байты дискового файла, даже если следующий fsync не удастся.
        free(s->snapshot); s->snapshot=mem_alloc(n+1); memcpy(s->snapshot,data,n); s->snapshot_len=n;
        // Пояснение: fsync каталога подтверждает устойчивость изменения его записи о файле.
        if(fsync(dirfd)!=0) {
            // Пояснение: Выделяем отдельный статус: файл уже заменён, но надёжность после сбоя питания не
            // Пояснение: подтверждена.
            result=SAVE_UNCERTAIN;
            // Пояснение: Объясняем пользователю, почему это отличается от обычной ошибки до замены.
            snprintf(err,ERR_SIZE,"Файл уже заменён, но диск не подтвердил синхронизацию каталога: %s. Решение есть в файле; надёжность при сбое питания не подтверждена. Повторите сохранение или проверьте копию перед выходом.",strerror(errno));
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Закрываем каталог, освобождаем имя временного файла и возвращаем точный статус.
    close(dirfd);free(temp);return result;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Вспомогательный путь из байтов заданной кодировки к разобранной Table.
static bool parse_bytes(const char *raw,size_t n,const char *encoding,char delimiter,bool xlsx,const char *sheet,Table *t,char err[ERR_SIZE]) {
    // XLSX уже содержит Unicode; кодировка и CSV-разделитель здесь не применяются.
    if(xlsx)return workbook_read(raw,n,sheet,t,err);
    // Пояснение: Преобразуем байты в UTF-8; при ошибке возвращаем false.
    size_t m;char *utf=convert_text(raw,n,encoding,"UTF-8",&m,err);if(!utf)return false;
    // Пояснение: Разбираем UTF-8, освобождаем временный текст и возвращаем успех.
    bool ok=table_parse(utf,m,delimiter,t,err);free(utf);return ok;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Проверяет совместимость исходника и ранее сохранённой рабочей копии.
static bool compatible(const Table *a,const Table *b) {
    // При продолжении сеанса совпадают не только значения, но лист и физические координаты строк.
    if((a->sheet!=NULL)!=(b->sheet!=NULL)||(a->sheet&&strcmp(a->sheet,b->sheet)))return false;
    // Пояснение: Число записей и столбцов должно совпадать.
    if(a->count!=b->count || a->columns!=b->columns) return false;
    // Пояснение: Сравниваем каждую ячейку, включая строку заголовка.
    for(size_t r=0;r<a->count;r++) for(size_t c=0;c<a->columns;c++) {
        // Перестановка или вставка физических строк Excel требует нового согласования книги.
        if(a->source_rows&&a->source_rows[r]!=b->source_rows[r])return false;
        // Пояснение: В данных разрешены различия только в action и label; заголовок сравниваем целиком.
        if(r && (c==a->col[ACTION] || c==a->col[LABEL])) continue;
        // Пояснение: Любое другое изменение, включая порядок записей, означает несовместимость.
        if(strcmp(a->rows[r].cells[c],b->rows[r].cells[c])) return false;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Все неизменяемые значения совпали.
    return true;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Открывает сеанс: нормализует пути, блокирует копию, читает исходник и продолжает либо создаёт
// Пояснение: копию.
bool store_open(Store *s,const char *input,const char *output,const char *encoding,char delimiter,char err[ERR_SIZE]) {
    // Старые вызывающие модули и CSV-тесты используют автоматический выбор листа.
    return store_open_sheet(s,input,output,encoding,delimiter,NULL,err);
}
// Расширенный вход Store для --sheet; прежний контракт сохранён обёрткой выше.
bool store_open_sheet(Store *s,const char *input,const char *output,const char *encoding,char delimiter,const char *sheet,char err[ERR_SIZE]) {
    // Пояснение: Обнуляем Store, задаём невалидный дескриптор -1 и очищаем текст ошибки.
    memset(s,0,sizeof *s); s->lock_fd=-1; err[0]=0;
    // Не выдаём CSV-байты за XLSX или наоборот при несовпадающих расширениях.
    s->xlsx=workbook_path(input);
    if(s->xlsx!=workbook_path(output)){snprintf(err,ERR_SIZE,"Для XLSX укажите исходник и рабочую копию с расширением .xlsx; CSV сохраняйте в CSV.");return false;}
    // Пояснение: Храним исходные байты отдельно, чтобы создать первую копию без пересериализации.
    char *source_bytes=NULL;size_t source_len=0;
    // Пояснение: Получаем существующий абсолютный путь исходника.
    s->input=realpath(input,NULL);
    // Пояснение: Отсутствие исходника ведёт к общей очистке.
    if(!s->input) { snprintf(err,ERR_SIZE,"Исходник недоступен: %s",strerror(errno)); goto fail; }
    // Пояснение: Структура метаданных исходника.
    struct stat st;
    // Пояснение: Без успешного stat не сможем проверить тождество файлов.
    if(stat(s->input,&st)!=0) { snprintf(err,ERR_SIZE,"Не удалось проверить исходник."); goto fail; }
    // Пояснение: Запоминаем устройство и inode исходника для защиты от жёстких ссылок.
    s->input_dev=st.st_dev; s->input_ino=st.st_ino;
    // Пояснение: Строим абсолютный выходной путь; при неудаче освобождаем всё через fail.
    s->output=canonical_output(output,err); if(!s->output) goto fail;
    // Пояснение: Сохраняем свою копию имени кодировки для будущих записей.
    s->encoding=str_copy(encoding);
    // Пояснение: Не продолжаем с выходным путём, который может повредить исходник.
    if(!protected_path(s,err)) goto fail;
    // Пояснение: Имя файла блокировки: путь рабочей копии плюс .lock.
    char *lock=mem_alloc(strlen(s->output)+6); sprintf(lock,"%s.lock",s->output);
    // Пояснение: Открываем lock с правами 0600; NOFOLLOW запрещает следовать ссылке, CLOEXEC не передаёт fd
    // Пояснение: дочерним программам.
    s->lock_fd=open(lock,O_CREAT|O_RDWR|O_CLOEXEC|O_NOFOLLOW,0600); free(lock);
    // Пояснение: Неблокирующая эксклюзивная flock предотвращает одновременный сеанс другого экземпляра.
    if(s->lock_fd<0 || flock(s->lock_fd,LOCK_EX|LOCK_NB)!=0) { snprintf(err,ERR_SIZE,"Рабочая копия занята другим экземпляром или блокировка недоступна."); goto fail; }
    // Пояснение: Читаем исходник в память и запоминаем точную длину.
    source_bytes=read_bytes(s->input,&source_len,err);if(!source_bytes)goto fail;
    // Пояснение: Разбираем исходник в таблицу с проверкой схемы.
    if(!parse_bytes(source_bytes,source_len,encoding,delimiter,s->xlsx,sheet,&s->table,err)) goto fail;
    // Пояснение: Если рабочая копия существует, запускаем восстановление сеанса.
    if(lstat(s->output,&st)==0) {
        // Пояснение: Повторно проверяем тип копии и отсутствие тождества исходнику.
        if(!protected_path(s,err)) goto fail;
        // Пояснение: Временная таблица для восстановленных решений.
        Table resumed={0};
        // Пояснение: Читаем байты копии один раз: именно они станут и таблицей, и снимком для сравнения.
        s->snapshot=read_bytes(s->output,&s->snapshot_len,err);if(!s->snapshot)goto fail;
        // Пояснение: Разбираем снимок, чтобы состояние памяти точно соответствовало сохранённому снимку.
        if(!parse_bytes(s->snapshot,s->snapshot_len,encoding,delimiter,s->xlsx,s->table.sheet,&resumed,err)) goto fail;
        // Пояснение: Несовместимую копию отклоняем с освобождением временной таблицы.
        if(!compatible(&s->table,&resumed)) { table_free(&resumed); snprintf(err,ERR_SIZE,"Рабочая копия не соответствует исходнику: записи или неизменяемые столбцы отличаются."); goto fail; }
        // Пояснение: Освобождаем таблицу исходника и принимаем восстановленную таблицу вместе с её памятью.
        table_free(&s->table); s->table=resumed;
    // Пояснение: Если копии нет, создаём её из исходных байтов.
    } else {
        // Пояснение: Первое создание должно закончиться SAVE_OK; неопределённый fsync тоже останавливает
        // Пояснение: открытие сеанса.
        if(atomic_write(s,source_bytes,source_len,err)!=SAVE_OK)goto fail;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Исходные байты больше не нужны: рабочее состояние уже находится в Store.
    free(source_bytes);
    // Пояснение: Сеанс готов для интерфейса.
    return true;
// Пояснение: Общая ветка ошибок освобождает байты и закрывает частично подготовленный Store.
fail: free(source_bytes);store_close(s); return false;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Применяет одно решение в памяти и записывает всю таблицу; при ошибке до замены откатывает ячейки.
SaveResult store_commit(Store *s,size_t row,const char *action,const char *label,char err[ERR_SIZE]) {
    // Пояснение: Сбрасываем сообщение предыдущей ошибки.
    err[0]=0;
    // Пояснение: Запрещаем заголовок, отсутствующую запись и неизвестные коды действий.
    if(!row || row>=s->table.count || (strcmp(action,"OK") && strcmp(action,"ERROR") && strcmp(action,"NOT_DESC"))) {
        // Пояснение: Сообщаем о недопустимом запросе без изменения таблицы.
        snprintf(err,ERR_SIZE,"Недопустимая запись или действие."); return SAVE_FAILED;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: a и l — адреса указателей на строки ячеек; через них можно заменить сами строки.
    char **a=&s->table.rows[row].cells[s->table.col[ACTION]], **l=&s->table.rows[row].cells[s->table.col[LABEL]];
    // Пояснение: Сохраняем старые адреса для освобождения после успеха либо возврата при неудаче.
    char *old_a=*a,*old_l=*l;
    // Пояснение: Устанавливаем независимые копии новых action и label в таблицу.
    *a=str_copy(action); *l=str_copy(label);
    // Готовим новые байты книги или CSV до атомарной записи.
    size_t m;char *raw;
    // Для XLSX точечно меняем ячейки последнего принятого снимка книги.
    if(s->xlsx) {
        unsigned changed=(strcmp(old_a,action)?1u:0u)|(strcmp(old_l,label)?2u:0u);
        raw=workbook_write(s->snapshot,s->snapshot_len,&s->table,row,changed,&m,err);
    }
    else {
        // Для CSV сохраняем прежний путь: сериализация UTF-8 → исходная кодировка.
        size_t n;char *utf=table_serialize(&s->table,&n);
        raw=convert_text(utf,n,"UTF-8",s->encoding,&m,err);free(utf);
    }
    // Пояснение: Если конвертация успешна, атомарно сохраняем байты; затем освобождаем их.
    SaveResult result=raw?atomic_write(s,raw,m,err):SAVE_FAILED; free(raw);
    // Пояснение: При SAVE_OK и SAVE_UNCERTAIN файл уже содержит новые данные: старые строки удаляем.
    if(result!=SAVE_FAILED) { free(old_a); free(old_l); }
    // Пояснение: Только при SAVE_FAILED удаляем новые строки и восстанавливаем прежние адреса ячеек.
    else { free(*a); free(*l); *a=old_a; *l=old_l; }
    // Пояснение: Передаём интерфейсу точный результат сохранения.
    return result;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Закрывает сеанс, освобождая память и удерживаемую блокировку.
void store_close(Store *s) {
    // Пояснение: Удаляем таблицу и все принадлежащие Store динамические строки.
    table_free(&s->table); free(s->input);free(s->output);free(s->encoding);free(s->snapshot);
    // Пояснение: Закрытие дескриптора lock снимает flock; сам маленький файл .lock может остаться.
    if(s->lock_fd>=0) close(s->lock_fd);
    // Пояснение: Возвращаем структуру в пустое состояние с невалидным lock_fd.
    memset(s,0,sizeof *s);s->lock_fd=-1;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
