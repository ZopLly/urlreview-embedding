// Пояснение: Ограничение входа: 256 × 1024 × 1024 байта; приведение к size_t задаёт тип размера.
#define INPUT_LIMIT ((size_t)256 * 1024 * 1024)
// Пояснение: Растущий буфер: data — память, len — занятые байты, cap — выделенная ёмкость.
typedef struct { char *data; size_t len, cap; } Buffer;

// Пояснение: Выделяет обнулённую память; при нехватке завершает процесс, поэтому callers не проверяют NULL.
void *mem_alloc(size_t n) {
    // Пояснение: calloc обнуляет память; даже для нулевого запроса выделяем один байт.
    void *p = calloc(n ? n : 1, 1);
    // Пояснение: NULL означает нехватку памяти: сообщение в stderr и код завершения 2.
    if (!p) { fputs("Недостаточно памяти.\n", stderr); exit(2); }
    // Пояснение: Передаём выделенную память вызывающему коду, который затем должен вызвать free.
    return p;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Меняет размер блока p; адрес после realloc может измениться.
void *mem_resize(void *p, size_t n) {
    // Пояснение: Нулевой размер заменяем единицей, чтобы realloc не освобождал блок неявно.
    void *q = realloc(p, n ? n : 1);
    // Пояснение: При ошибке расширения дальнейшая работа невозможна: выводим сообщение и завершаемся.
    if (!q) { fputs("Недостаточно памяти.\n", stderr); exit(2); }
    // Пояснение: Возвращаем новый адрес блока, который нужно сохранить вместо старого.
    return q;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Создаёт независимую динамическую копию строки s.
char *str_copy(const char *s) {
    // Пояснение: strlen не считает завершающий ноль: добавляем 1, выделяем память, копируем и возвращаем.
    size_t n = strlen(s) + 1; char *p = mem_alloc(n); memcpy(p, s, n); return p;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Добавляет n байтов из s в конец буфера b; static ограничивает функцию этим файлом.
static void append(Buffer *b, const char *s, size_t n) {
    // Пояснение: Проверяем, хватит ли ёмкости на старый текст, добавку и завершающий ноль.
    if (b->len + n + 1 > b->cap) {
        // Пояснение: Оставляем запас вдвое больше необходимого, уменьшая число перераспределений памяти.
        b->cap = (b->len + n + 1) * 2;
        // Пояснение: Сохраняем новый адрес блока после расширения.
        b->data = mem_resize(b->data, b->cap);
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Копируем в свободный хвост, увеличиваем длину и завершаем строку нулевым байтом.
    memcpy(b->data + b->len, s, n); b->len += n; b->data[b->len] = 0;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Обёртка над append: передаём адрес одного символа и длину 1.
static void put(Buffer *b, char ch) { append(b, &ch, 1); }
// Пояснение: Читает обычный файл в выделенную память; размер отдаёт через len, причину сбоя через err.
char *read_bytes(const char *path, size_t *len, char err[ERR_SIZE]) {
    // Пояснение: Открываем файл для чтения байтов, без преобразования текста.
    FILE *f = fopen(path, "rb");
    // Пояснение: При ошибке открытия записываем системную причину в ограниченный буфер и возвращаем NULL.
    if (!f) { snprintf(err, ERR_SIZE, "Не удалось открыть файл: %s", strerror(errno)); return NULL; }
    // Пояснение: Структура для типа и размера уже открытого файла.
    struct stat st;
    // Пояснение: fstat проверяет дескриптор: допускаем только обычный файл с размером от 0 до лимита.
    if (fstat(fileno(f), &st) || !S_ISREG(st.st_mode) || st.st_size < 0 || (size_t)st.st_size > INPUT_LIMIT) {
        // Пояснение: Отклоняем неподходящий файл; закрываем поток перед возвратом.
        snprintf(err, ERR_SIZE, "Нужен обычный файл размером не более 256 МиБ."); fclose(f); return NULL;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Обнуляем растущий буфер и готовим блок чтения 64 КиБ и счётчик прочитанного.
    Buffer b = {0}; char block[65536]; size_t n;
    // Пояснение: Читаем блоками до конца файла; n получает фактическое число байтов очередного блока.
    while ((n = fread(block, 1, sizeof block, f)) != 0) {
        // Пояснение: Повторно проверяем лимит: файл мог вырасти после fstat; при превышении освобождаем
        // Пояснение: ресурсы.
        if (b.len + n > INPUT_LIMIT) { snprintf(err, ERR_SIZE, "Файл превышает 256 МиБ."); free(b.data); fclose(f); return NULL; }
        // Пояснение: Добавляем прочитанный блок к общему содержимому.
        append(&b, block, n);
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Запоминаем ошибку чтения до закрытия потока.
    bool failed = ferror(f) != 0;
    // Пояснение: Ошибку закрытия тоже считаем неудачным чтением.
    if (fclose(f) != 0) failed = true;
    // Пояснение: При сбое удаляем частичный результат и возвращаем NULL.
    if (failed) { snprintf(err, ERR_SIZE, "Ошибка чтения файла."); free(b.data); return NULL; }
    // Пояснение: Пустой файл тоже возвращаем как выделенную пустую строку, а не NULL ошибки.
    if (!b.data) b.data = str_copy("");
    // Пояснение: Записываем длину через указатель len и передаём владение байтами вызывающему коду.
    *len = b.len; return b.data;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Преобразует кодировку from → to; ошибки символов не заменяет вопросительными знаками.
char *convert_text(const char *data, size_t len, const char *from, const char *to, size_t *out_len, char err[ERR_SIZE]) {
    // Пояснение: Создаём преобразователь iconv: сначала целевая, затем исходная кодировка.
    iconv_t cd = iconv_open(to, from);
    // Пояснение: Специальное значение -1 означает, что преобразователь создать не удалось.
    if (cd == (iconv_t)-1) { snprintf(err, ERR_SIZE, "Неизвестная кодировка: %s → %s", from, to); return NULL; }
    // Пояснение: Выделяем запас до четырёх выходных байтов на входной и место для завершающего нуля.
    size_t capacity = len * 4 + 16, left = capacity - 1, inleft = len;
    // Пояснение: result сохраняет начало блока; out и in будут перемещаться во время преобразования.
    char *result = mem_alloc(capacity), *out = result, *in = (char *)data;
    // Пояснение: iconv двигает указатели и уменьшает остатки; -1 означает ошибку.
    bool ok = iconv(cd, &in, &inleft, &out, &left) != (size_t)-1;
    // Пояснение: Сбрасываем внутреннее состояние кодировки и записываем завершающую последовательность, если
    // Пояснение: нужна.
    if (ok) ok = iconv(cd, NULL, NULL, &out, &left) != (size_t)-1;
    // Пояснение: Освобождаем дескриптор преобразователя независимо от результата.
    iconv_close(cd);
    // Пояснение: Отдельная ветка обработки ошибки преобразования.
    if (!ok) {
        // Пояснение: Позицию ошибки получаем как исходная длина минус непрочитанный остаток.
        snprintf(err, ERR_SIZE, "Ошибка кодировки %s → %s: неверный или непредставимый символ (байт %zu).", from, to, len-inleft);
        // Пояснение: Освобождаем непригодный результат и возвращаем NULL.
        free(result); return NULL;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Разность указателей даёт длину; дописываем ноль и возвращаем начало выходного блока.
    *out_len = (size_t)(out - result); *out = 0; return result;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Освобождает вложенную память таблицы; порядок важен: строки ячеек → массивы → таблица.
void table_free(Table *t) {
    // Пояснение: Перебираем записи вместе с заголовком, начиная с нулевой.
    for (size_t r = 0; r < t->count; r++) {
        // Пояснение: Освобождаем текст каждой ячейки текущей записи.
        for (size_t c = 0; c < t->rows[r].count; c++) free(t->rows[r].cells[c]);
        // Пояснение: Теперь освобождаем массив указателей на ячейки.
        free(t->rows[r].cells);
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Освобождаем массив записей и обнуляем поля структуры, предотвращая повторное использование
    // Пояснение: адресов.
    free(t->rows); free(t->sheet); free(t->source_rows); memset(t, 0, sizeof *t);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Завершает текущее поле CSV и передаёт его память записи.
static void finish_field(Row *row, Buffer *b) {
    // Пояснение: Расширяем массив ячеек ровно на один указатель.
    row->cells = mem_resize(row->cells, (row->count + 1) * sizeof *row->cells);
    // Пояснение: Сохраняем текст или выделенную пустую строку; очищаем буфер без free, потому что память уже у
    // Пояснение: Row.
    row->cells[row->count++] = b->data ? b->data : str_copy(""); memset(b, 0, sizeof *b);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Завершает запись CSV и передаёт её ячейки таблице.
static void finish_row(Table *t, Row *row) {
    // Пояснение: Расширяем массив записей на одну структуру Row.
    t->rows = mem_resize(t->rows, (t->count + 1) * sizeof *t->rows);
    // Пояснение: Копируем структуру с указателями в таблицу и обнуляем временную Row, передав владение.
    t->rows[t->count++] = *row; memset(row, 0, sizeof *row);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Проверяет обязательные заголовки, число полей и допустимые действия после разбора CSV.
static bool schema(Table *t, char err[ERR_SIZE]) {
    // Пояснение: Имена соответствуют логическим индексам DOMAIN, CLASS, LABEL, ACTION, DESCRIPTION из core.h.
    static const char *names[] = {"domain", "class", "label", "action", "description"};
    // Пояснение: Без записи заголовка невозможно определить структуру таблицы.
    if (!t->count) { snprintf(err, ERR_SIZE, "CSV пуст: отсутствует заголовок."); return false; }
    // Пояснение: Число столбцов задаёт первая запись — заголовок.
    t->columns = t->rows[0].count;
    // Пояснение: Для каждого обязательного имени ищем его физическое положение в заголовке.
    for (size_t k = 0; k < COLUMN_COUNT; k++) {
        // Пояснение: Начинаем счётчик совпадений заново для каждого имени.
        size_t found = 0;
        // Пояснение: strcmp возвращает 0 при равенстве; запоминаем позицию имени и число совпадений.
        for (size_t c = 0; c < t->columns; c++) if (!strcmp(t->rows[0].cells[c], names[k])) { t->col[k] = c; found++; }
        // Пояснение: Каждое обязательное имя должно встретиться ровно один раз: ни пропусков, ни дублей.
        if (found != 1) { snprintf(err, ERR_SIZE, "Нужен ровно один столбец '%s'. Проверьте разделитель и кодировку.", names[k]); return false; }
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Проверяем данные с записи 1: нулевая содержит заголовок.
    for (size_t r = 1; r < t->count; r++) {
        // Пояснение: Выявляем строки с лишними или недостающими полями.
        if (t->rows[r].count != t->columns) {
            // Пояснение: Сообщаем номер записи, фактическое и ожидаемое число полей.
            snprintf(err, ERR_SIZE, "Запись %zu: %zu полей вместо %zu.", r, t->rows[r].count, t->columns); return false;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: Берём action через найденную позицию столбца, а не фиксированный номер CSV.
        const char *a = cell(t, r, ACTION);
        // Пояснение: Непустой action разрешён только при точном совпадении с одним из трёх кодов.
        if (*a && strcmp(a,"OK") && strcmp(a,"ERROR") && strcmp(a,"NOT_DESC")) {
            // Пояснение: Неизвестный action отклоняем, чтобы не считать ошибочные статусы проверенными.
            snprintf(err, ERR_SIZE, "Запись %zu: неизвестное значение action. Ожидается OK, ERROR, NOT_DESC или пусто.", r); return false;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Все проверки структуры и статусов прошли.
    return true;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Разбирает UTF-8 CSV побайтово; состояние отличает разделители данных от разделителей формата.
bool table_parse(const char *text, size_t len, char delimiter, Table *t, char err[ERR_SIZE]) {
    // Пояснение: Обнуляем результат, сохраняем разделитель и задаём LF до обнаружения настоящего перевода
    // Пояснение: строки.
    memset(t, 0, sizeof *t); t->delimiter = delimiter; strcpy(t->eol, "\n");
    // Пояснение: Четыре состояния: начало поля, обычный текст, внутри кавычек, после закрывающей кавычки.
    enum { START, PLAIN, QUOTED, CLOSED } state = START;
    // Пояснение: field и row накапливают данные; pending помнит незавершённую запись, eol_seen — найденный
    // Пояснение: стиль строк.
    Buffer field = {0}; Row row = {0}; bool pending = false, eol_seen = false;
    // Пояснение: Индекс текущего байта во входном тексте.
    size_t i = 0;
    // Пояснение: Пропускаем UTF-8 BOM, но запоминаем его наличие для последующего сохранения.
    if (len >= 3 && !memcmp(text, "\xef\xbb\xbf", 3)) { t->bom = true; i = 3; }
    // Пояснение: Идём по байтам; UTF-8 внутри полей копируется без изменения последовательностей.
    for (; i < len; i++) {
        // Пояснение: Берём текущий байт.
        char ch = text[i];
        // Пояснение: Нулевой байт запрещён, поскольку строки C завершаются нулём; переходим к общей очистке.
        if (!ch) { snprintf(err, ERR_SIZE, "CSV содержит нулевой байт."); goto fail; }
        // Пояснение: Теперь есть данные, которые нужно завершить даже при отсутствии перевода строки в конце.
        pending = true;
        // Пояснение: Внутри кавычек разделитель и переносы являются содержимым поля.
        if (state == QUOTED) {
            // Пояснение: Кавычка внутри quoted-поля пока считается возможной закрывающей.
            if (ch == '"') state = CLOSED;
            // Пояснение: Остальные байты внутри кавычек копируем буквально, включая переводы строк.
            else put(&field, ch);
            // Пояснение: Не запускаем обработку разделителей для байта внутри quoted-поля.
            continue;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: Две кавычки подряд означают одну кавычку в данных; возвращаемся внутрь quoted-поля.
        if (state == CLOSED && ch == '"') { put(&field, '"'); state = QUOTED; continue; }
        // Пояснение: Разделитель вне кавычек завершает поле и начинает следующее, включая пустое.
        if (ch == delimiter) { finish_field(&row, &field); state = START; continue; }
        // Пояснение: CR или LF вне кавычек завершает логическую CSV-запись.
        if (ch == '\n' || ch == '\r') {
            // Пояснение: Распознаём пару CRLF как один межзаписный перевод строки.
            bool crlf = ch == '\r' && i+1 < len && text[i+1] == '\n';
            // Пояснение: Сохраняем первый обнаруженный стиль перевода строки для сериализации.
            if (!eol_seen) { strcpy(t->eol, crlf ? "\r\n" : ch == '\r' ? "\r" : "\n"); eol_seen = true; }
            // Пояснение: Второй байт CRLF уже учтён: пропускаем его.
            if (crlf) i++;
            // Пояснение: Заканчиваем поле и запись, сбрасываем состояние и pending, затем продолжаем цикл.
            finish_field(&row, &field); finish_row(t, &row); state = START; pending = false; continue;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: После закрывающей кавычки допустимы только уже обработанные разделители; иной байт —
        // Пояснение: ошибка.
        if (state == CLOSED) { snprintf(err, ERR_SIZE, "Запись %zu: символ после закрывающей кавычки.", t->count+1); goto fail; }
        // Пояснение: Проверяем, не начинается ли quoted-поле.
        if (ch == '"') {
            // Пояснение: Кавычка может открывать поле только в START; внутри обычного текста она недопустима.
            if (state != START) { snprintf(err, ERR_SIZE, "Запись %zu: кавычка внутри незакавыченного поля.", t->count+1); goto fail; }
            // Пояснение: Переходим к чтению содержимого в кавычках.
            state = QUOTED;
        // Пояснение: Обычный байт добавляем в поле и отмечаем, что поле уже не пустое начало.
        } else { put(&field, ch); state = PLAIN; }
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Дойдя до конца внутри QUOTED, сообщаем о незакрытой кавычке.
    if (state == QUOTED) { snprintf(err, ERR_SIZE, "CSV: незакрытая кавычка."); goto fail; }
    // Пояснение: Завершаем последнюю запись без перевода строки; после готового EOL лишнюю запись не создаём.
    if (pending) { finish_field(&row, &field); finish_row(t, &row); }
    // Пояснение: Проверяем схему уже разобранной таблицы; ошибка ведёт к той же очистке памяти.
    if (!schema(t, err)) goto fail;
    // Пояснение: Парсинг и проверка таблицы завершились успешно.
    return true;
// Пояснение: Метка общей очистки для всех ошибок разбора; goto переносит выполнение сюда.
fail:
    // Пояснение: Удаляем ещё не переданный записи буфер поля.
    free(field.data);
    // Пояснение: Освобождаем ячейки незавершённой записи.
    for (size_t c = 0; c < row.count; c++) free(row.cells[c]);
    // Пояснение: Освобождаем её массив и уже собранную таблицу; возвращаем false.
    free(row.cells); table_free(t); return false;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Соединяет чтение файла, преобразование кодировки и CSV-парсер.
bool table_read(const char *path, const char *encoding, char delimiter, Table *t, char err[ERR_SIZE]) {
    // Обратная совместимость: без --sheet backend выбирает единственный подходящий лист.
    return table_read_sheet(path,encoding,delimiter,NULL,t,err);
}
// Общий вход чтения файла: расширение определяет CSV либо OOXML.
bool table_read_sheet(const char *path,const char *encoding,char delimiter,const char *sheet,Table *t,char err[ERR_SIZE]) {
    // Пояснение: Читаем исходные байты; при ошибке прекращаем работу с уже заполненным err.
    size_t n, m; char *raw = read_bytes(path, &n, err); if (!raw) return false;
    // Бинарный XLSX нельзя передавать в iconv: сначала распаковываем через workbook_read.
    if(workbook_path(path)) {bool ok=workbook_read(raw,n,sheet,t,err);free(raw);return ok;}
    // Пояснение: Переводим в внутренний UTF-8 и освобождаем исходные байты.
    char *utf = convert_text(raw, n, encoding, "UTF-8", &m, err); free(raw);
    // Пояснение: Если конвертация не удалась, парсер не вызываем.
    if (!utf) return false;
    // Пояснение: Разбираем UTF-8, освобождаем временный текст и возвращаем результат парсера.
    bool ok = table_parse(utf, m, delimiter, t, err); free(utf); return ok;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Превращает Table в выделенную строку UTF-8 CSV, сохраняя значения всех ячеек.
char *table_serialize(const Table *t, size_t *len) {
    // Пояснение: Начинаем с пустого выходного буфера.
    Buffer out = {0};
    // Пояснение: Восстанавливаем BOM, если он был у загруженной таблицы.
    if (t->bom) append(&out, "\xef\xbb\xbf", 3);
    // Пояснение: Сериализуем все записи, включая заголовок.
    for (size_t r = 0; r < t->count; r++) {
        // Пояснение: Перебираем столбцы текущей записи.
        for (size_t c = 0; c < t->columns; c++) {
            // Пояснение: Перед каждым полем, кроме первого, вставляем разделитель.
            if (c) put(&out, t->delimiter);
            // Пояснение: Берём текст ячейки и пока предполагаем, что кавычки не нужны.
            const char *s = t->rows[r].cells[c]; bool quote = false;
            // Пояснение: Разделитель, кавычка или перевод строки внутри данных требуют quoted-поля.
            for (const char *p = s; *p; p++) if (*p == t->delimiter || *p == '"' || *p == '\n' || *p == '\r') quote = true;
            // Пояснение: При необходимости открываем поле кавычкой.
            if (quote) put(&out, '"');
            // Пояснение: Копируем текст; каждую кавычку удваиваем по правилам CSV.
            for (; *s; s++) { if (*s == '"') put(&out, '"'); put(&out, *s); }
            // Пояснение: Закрываем quoted-поле второй внешней кавычкой.
            if (quote) put(&out, '"');
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: После каждой записи добавляем сохранённый межзаписный перевод строки.
        append(&out, t->eol, strlen(t->eol));
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Возвращаем длину и выделенную строку; даже пустой результат имеет освобождаемый адрес.
    *len = out.len; return out.data ? out.data : str_copy("");
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Логический столбец column переводим через col в реальное положение ячейки данной записи.
const char *cell(const Table *t, size_t row, int column) { return t->rows[row].cells[t->col[column]]; }
// Пояснение: Подсчитывает проверенные записи по непустому action в таблице с уже проверенной схемой.
size_t reviewed_count(const Table *t) {
    // Пояснение: Начальное число проверенных равно нулю.
    size_t count = 0;
    // Пояснение: Заголовок пропускаем; каждая запись с непустым допустимым action добавляет единицу.
    for (size_t r = 1; r < t->count; r++) if (*cell(t,r,ACTION)) count++;
    // Пояснение: Возвращаем число проверенных, а не количество выполненных сохранений.
    return count;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
