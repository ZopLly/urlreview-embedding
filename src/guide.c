// О файле: Загрузка TSV-справочника: четыре поля через табуляцию — код, пояснение, включения, исключения. Каждая Category владеет своими копиями строк.
// Пояснение: Подключаем guide.h: типы и функции справочника категорий.
#include "guide.h"
// Пояснение: Подключаем ctype.h: проверки символов isalnum/isspace.
#include <ctype.h>
// Пояснение: Подключаем stdio.h: файловые потоки FILE, printf, snprintf и ввод/вывод.
#include <stdio.h>
// Пояснение: Подключаем stdlib.h: выделение и освобождение памяти, exit и другие базовые функции.
#include <stdlib.h>
// Пояснение: Подключаем string.h: strlen, strcmp, memcpy, memset и другие операции строк/байтов.
#include <string.h>

// Пояснение: Освобождает весь справочник, начиная с вложенных строк.
void guide_free(Guide *g) {
    // Пояснение: Перебираем созданные категории.
    for(size_t i=0;i<g->count;i++) {
        // Пояснение: Удаляем код и короткое пояснение.
        free(g->items[i].code); free(g->items[i].title);
        // Пояснение: Удаляем тексты включений и исключений.
        free(g->items[i].includes); free(g->items[i].excludes);
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Удаляем массив категорий и обнуляем Guide.
    free(g->items); memset(g,0,sizeof *g);
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Читает UTF-8 TSV, проверяет формат и уникальность кодов.
bool guide_read(const char *path,Guide *g,char err[ERR_SIZE]) {
    // Пояснение: Обнуляем результат; n и m будут длинами исходных и проверенных байтов.
    memset(g,0,sizeof *g); size_t n,m;
    // Пояснение: Загружаем файл с общей проверкой размера; NULL означает ошибку.
    char *raw=read_bytes(path,&n,err); if(!raw) return false;
    // Пояснение: Нулевые байты несовместимы со строками C, поэтому отклоняем файл.
    if(memchr(raw,0,n)) { free(raw); snprintf(err,ERR_SIZE,"Справочник содержит нулевой байт."); return false; }
    // Пояснение: Конвертация UTF-8 → UTF-8 служит валидацией; исходные байты освобождаем.
    char *data=convert_text(raw,n,"UTF-8","UTF-8",&m,err); free(raw); if(!data) return false;
    // Пояснение: Начинаем с первой строки TSV.
    char *line=data;
    // Пояснение: Продолжаем, пока строка не пуста на текущей позиции.
    while(*line) {
        // Пояснение: Находим LF и временно заменяем нулём, выделяя одну строку внутри общего буфера.
        char *end=strchr(line,'\n'); if(end) *end=0;
        // Пояснение: Убираем CR перед LF для справочника с Windows-переносами.
        size_t len=strlen(line); if(len && line[len-1]=='\r') line[len-1]=0;
        // Пояснение: Пустые строки пропускаем, непустые разбираем.
        if(*line) {
            // Пояснение: Массив из четырёх указателей; первое поле начинается с начала строки.
            char *parts[4]; parts[0]=line;
            // Пояснение: Ищем три табуляции, разделяющие четыре поля.
            for(size_t i=1;i<4;i++) {
                // Пояснение: Следующая табуляция находится после предыдущего поля.
                char *tab=strchr(parts[i-1],'\t');
                // Пояснение: Без обязательного разделителя структура строки неверна.
                if(!tab) goto invalid;
                // Пояснение: Заменяем табуляцию нулём и запоминаем начало следующего поля.
                *tab=0;parts[i]=tab+1;
            // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
            }
            // Пояснение: Запрещаем пятое поле и пустые код, пояснение или включения; исключения могут быть
            // Пояснение: пустыми.
            if(strchr(parts[3],'\t') || !*parts[0] || !*parts[1] || !*parts[2]) goto invalid;
            // Пояснение: Код состоит из ASCII-букв обоих регистров, цифр и подчёркивания; регистр сохраняется.
            for(const char *p=parts[0];*p;p++) if(!(*p>='a'&&*p<='z') && !(*p>='A'&&*p<='Z') && !(*p>='0'&&*p<='9') && *p!='_') goto invalid;
            // Пояснение: Проверяем код против всех уже добавленных категорий, отклоняя дубликат.
            for(size_t i=0;i<g->count;i++) if(!strcmp(g->items[i].code,parts[0])) goto invalid;
            // Пояснение: Расширяем массив на одну Category.
            g->items=mem_resize(g->items,(g->count+1)*sizeof *g->items);
            // Пояснение: Получаем адрес нового элемента и увеличиваем число категорий.
            Category *c=&g->items[g->count++];
            // Пояснение: Копируем каждое поле отдельно, потому что общий буфер data затем будет освобождён.
            c->code=str_copy(parts[0]);c->title=str_copy(parts[1]);c->includes=str_copy(parts[2]);c->excludes=str_copy(parts[3]);
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: Без LF это последняя строка: завершаем цикл.
        if(!end) break;
        // Пояснение: Переходим к байту после найденного LF.
        line=end+1;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Общий буфер TSV больше не нужен, категории уже содержат независимые строки.
    free(data);
    // Пояснение: Непустой корректно прочитанный справочник означает успех.
    if(g->count) return true;
    // Пояснение: Пустой справочник возвращает false с понятным сообщением.
    snprintf(err,ERR_SIZE,"Справочник пуст.");return false;
// Пояснение: Общая ветка ошибки формата или дубликата.
invalid:
    // Пояснение: Указываем номер следующей категории по счётчику; пустые пропущенные строки этот счётчик не
    // Пояснение: увеличивают.
    snprintf(err,ERR_SIZE,"Неверная или повторяющаяся категория в строке %zu справочника.",g->count+1);
    // Пояснение: Удаляем исходный текст и частично созданный справочник перед возвратом false.
    free(data);guide_free(g);return false;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
