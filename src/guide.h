// О файле: Контракт справочника категорий: загрузка TSV и управление памятью категорий.
// Пояснение: Защита заголовка: читаем содержимое только если его уникальный макрос ещё не определён.
#ifndef URL_REVIEW_GUIDE_H
// Пояснение: Отмечаем заголовок как подключённый, чтобы повторный #include не дублировал определения.
#define URL_REVIEW_GUIDE_H
// Пояснение: Подключаем core.h: общие типы Table/Store и функции CSV, памяти и сохранения.
#include "core.h"
// Пояснение: Категория владеет четырьмя строками: кодом, кратким пояснением, включениями и исключениями.
typedef struct { char *code, *title, *includes, *excludes; } Category;
// Пояснение: Массив категорий и его длина; порядок задаёт постоянные экранные номера.
typedef struct { Category *items; size_t count; } Guide;
// Пояснение: Загружает справочник по пути; при false заполняет err.
bool guide_read(const char *path, Guide *guide, char err[ERR_SIZE]);
// Пояснение: Освобождает строки категорий и массив, затем обнуляет Guide.
void guide_free(Guide *guide);
// Пояснение: Конец условного включения заголовка.
#endif
