// Пояснение: Вычисляет путь data/categories.tsv относительно установленного исполняемого файла.
static char *default_guide(const char *arg0) {
    // Пояснение: Linux readlink читает путь текущего процесса; оставляем байт для завершающего нуля.
    char executable[4096]; ssize_t n=readlink("/proc/self/exe",executable,sizeof executable-1);
    // Пояснение: Переменная для динамической копии пути.
    char *path;
    // Пояснение: readlink не добавляет ноль: ставим его и копируем путь.
    if(n>0) { executable[n]=0;path=str_copy(executable); }
    // Пояснение: Резервный путь: realpath аргумента запуска; если недоступен, используем относительный путь
    // Пояснение: справочника.
    else { path=realpath(arg0,NULL); if(!path) return str_copy("data/categories.tsv"); }
    // Пояснение: Отсекаем имя бинарника по последнему слешу, оставляя каталог.
    char *slash=strrchr(path,'/');if(slash) *slash=0;
    // Пояснение: Выделяем память, добавляем путь справочника, освобождаем исходный путь и возвращаем результат.
    char *result=mem_alloc(strlen(path)+32);sprintf(result,"%s/data/categories.tsv",path);free(path);return result;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: ОС передаёт число аргументов argc и массив строк argv; argv[0] — имя запуска.
int main(int argc,char **argv) {
    // Пояснение: Подключаем локаль окружения; при неудаче пробуем C.UTF-8.
    if(!setlocale(LC_ALL,"")) setlocale(LC_ALL,"C.UTF-8");
    // Пояснение: Если локаль однобайтовая, отдельно пробуем UTF-8 для обработки символов.
    if(MB_CUR_MAX==1 && !setlocale(LC_CTYPE,"C.UTF-8")) {
        // Пояснение: Без доступной UTF-8 локали выдаём ошибку и код завершения 1.
        fputs("Для интерфейса нужна UTF-8 locale (например C.UTF-8).\n",stderr);return 1;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Начальные настройки: путей ещё нет, кодировка по умолчанию UTF-8.
    const char *input=NULL,*output=NULL,*encoding="UTF-8",*guide_path=NULL,*embedding_path=NULL,*sheet=NULL;
    // Пояснение: По умолчанию разделитель — точка с запятой, режим проверки выключен.
    char delimiter=';';bool check=false;
    // Пояснение: Перебираем аргументы после имени программы.
    for(int i=1;i<argc;i++) {
        // Пояснение: --help или -h печатает справку и завершает процесс успешно.
        if(!strcmp(argv[i],"--help") || !strcmp(argv[i],"-h")) { usage();return 0; }
        // Пояснение: --check включает проверку и переходит к следующему аргументу.
        if(!strcmp(argv[i],"--check")) { check=true;continue; }
        // Пояснение: Эти четыре параметра требуют следующего аргумента-значения.
        if(!strcmp(argv[i],"--encoding") || !strcmp(argv[i],"--delimiter") || !strcmp(argv[i],"--guide") || !strcmp(argv[i],"--embeddings") || !strcmp(argv[i],"--sheet")) {
            // Пояснение: Сохраняем имя параметра до сдвига индекса.
            const char *option=argv[i];
            // Пояснение: Увеличиваем i и проверяем, существует ли значение; иначе сообщаем ошибку.
            if(++i>=argc) { fprintf(stderr,"Нужно значение для %s\n",option);return 1; }
            // Пояснение: Отдельно обрабатываем параметр кодировки.
            if(!strcmp(option,"--encoding")) {
                // Пояснение: strcasecmp сравнивает без учёта регистра; нормализуем имя UTF-8.
                if(!strcasecmp(argv[i],"utf-8")) encoding="UTF-8";
                // Пояснение: Разрешаем два имени Windows-1251 и сохраняем каноническое.
                else if(!strcasecmp(argv[i],"windows-1251") || !strcasecmp(argv[i],"cp1251")) encoding="WINDOWS-1251";
                // Пояснение: Другие кодировки отклоняем.
                else { fputs("Кодировка: UTF-8 или windows-1251.\n",stderr);return 1; }
            // Пояснение: Запоминаем явно переданный путь TSV-справочника.
            } else if(!strcmp(option,"--guide")) guide_path=argv[i];
            // Имя листа передаётся в backend без изменения регистра или пробелов.
            else if(!strcmp(option,"--sheet")) sheet=argv[i];
            // Пояснение: Запоминаем явно переданный путь индекса .uremb.
            else if(!strcmp(option,"--embeddings")) embedding_path=argv[i];
            // Пояснение: Слова tab и буквальная последовательность обратный слеш+t означают байт табуляции.
            else if(!strcmp(argv[i],"tab") || !strcmp(argv[i],"\\t")) delimiter='\t';
            // Пояснение: Для разрешённых односимвольных разделителей берём первый символ аргумента.
            else if(!strcmp(argv[i],";") || !strcmp(argv[i],",")) delimiter=argv[i][0];
            // Пояснение: Неизвестный разделитель приводит к ошибке запуска.
            else { fputs("Разделитель: ; , или tab.\n",stderr);return 1; }
        // Пояснение: Остальные аргументы с начальным дефисом считаем неизвестными параметрами.
        } else if(argv[i][0]=='-') { fprintf(stderr,"Неизвестный параметр: %s\n",argv[i]);return 1; }
        // Пояснение: Первый позиционный аргумент задаёт исходный CSV.
        else if(!input) input=argv[i];
        // Пояснение: Второй позиционный аргумент задаёт рабочую копию.
        else if(!output) output=argv[i];
        // Пояснение: Больше двух путей не допускается.
        else { fputs("Лишний путь в аргументах.\n",stderr);return 1; }
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Нужен исходник и ровно один выходной путь при обычном запуске; в --check выходной путь
    // Пояснение: запрещён.
    if(!input || (!check&&!output) || (check&&output)) { usage();return 1; }
    // Пояснение: Буфер для подробного сообщения об ошибке из вызываемых модулей.
    char err[ERR_SIZE];
    // Пояснение: В режиме --check выполняем только чтение и проверки.
    if(check) {
        // Пояснение: Создаём пустую структуру таблицы.
        Table t={0};
        // Пояснение: Читаем CSV с выбранными кодировкой и разделителем; ошибку печатаем в stderr.
        if(!table_read_sheet(input,encoding,delimiter,sheet,&t,err)) { fprintf(stderr,"%s\n",err);return 1; }
        // Пояснение: count включает заголовок, поэтому число сайтов равно count-1.
        printf("Таблица корректна. Записей: %zu; проверено: %zu; столбцов: %zu.\n",t.count-1,reviewed_count(&t),t.columns);
        // Сообщаем, какой лист действительно выбран автоматически либо через --sheet.
        if(t.sheet)printf("Лист XLSX: %s\n",t.sheet);
        // Пояснение: Пустой необязательный индекс безопасно освобождать даже без загрузки.
        Embedding index={0};
        // Пояснение: Если индекс указан, проверяем его формат и соответствие этой таблице.
        if(embedding_path&&!embedding_read(embedding_path,&t,&index,err)) {
            // Пояснение: При ошибке индекса освобождаем таблицу и завершаем проверку.
            fprintf(stderr,"%s\n",err);table_free(&t);return 1;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: Сообщаем об успешной совместимости только при указанном индексе.
        if(embedding_path)puts("Индекс совместим с таблицей.");
        // Пояснение: Освобождаем память режима проверки и возвращаем успех.
        embedding_free(&index);table_free(&t);return 0;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Интерактивный интерфейс требует терминал и на входе, и на выходе.
    if(!isatty(STDIN_FILENO) || !isatty(STDOUT_FILENO)) { fputs("Запустите приложение в терминале. Для проверки без интерфейса используйте --check.\n",stderr);return 1; }
    // Пояснение: Находим справочник по умолчанию и подготавливаем структуру Guide.
    char *guide_default=default_guide(argv[0]); Guide guide;
    // Пояснение: Явный --guide имеет приоритет; при ошибке освобождаем вычисленный путь.
    if(!guide_read(guide_path?guide_path:guide_default,&guide,err)) { fprintf(stderr,"Справочник: %s\n",err);free(guide_default);return 1; }
    // Пояснение: Строка пути после чтения справочника больше не нужна.
    free(guide_default);
    // Пояснение: Подготавливаем хранилище состояния рабочего сеанса.
    Store store;
    // Пояснение: Открываем или создаём копию; при ошибке удаляем уже загруженный справочник.
    if(!store_open_sheet(&store,input,output,encoding,delimiter,sheet,err)) { fprintf(stderr,"%s\n",err);guide_free(&guide);return 1; }
    // Пояснение: Начальное пустое состояние необязательного индекса.
    Embedding index={0};
    // Пояснение: Загружаем указанный индекс против таблицы Store, которая может содержать восстановленные
    // Пояснение: решения.
    if(embedding_path&&!embedding_read(embedding_path,&store.table,&index,err)) {
        // Пояснение: При ошибке индекса закрываем Store и справочник перед выходом.
        fprintf(stderr,"%s\n",err);store_close(&store);guide_free(&guide);return 1;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Передаём готовые компоненты в основной цикл интерфейса и ждём его окончания.
    int result=ui_run(&store,&guide,&index);
    // Пояснение: Освобождаем массив векторов после закрытия интерфейса.
    embedding_free(&index);
    // Пояснение: Закрываем хранилище, освобождаем справочник и возвращаем код интерфейса операционной системе.
    store_close(&store);guide_free(&guide);return result;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
