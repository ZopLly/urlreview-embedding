// Пояснение: Читает беззнаковое 32-битное число из четырёх байтов little-endian независимо от порядка байтов
// Пояснение: машины.
static uint32_t little32(const unsigned char *p) {
    // Пояснение: Приводим каждый байт к uint32_t, сдвигаем на 0/8/16/24 бита и объединяем побитовым ИЛИ.
    return (uint32_t)p[0]|(uint32_t)p[1]<<8|(uint32_t)p[2]<<16|(uint32_t)p[3]<<24;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Вычисляет FNV-1a отпечаток domain + нулевой байт + description; алгоритм совпадает с Python.
static uint64_t fingerprint(const char *domain,const char *description) {
    // Пояснение: Начальное значение 64-битного FNV-1a; UINT64_C задаёт нужный тип целой константы.
    uint64_t h=UINT64_C(14695981039346656037);
    // Пояснение: Читаем домен как беззнаковые байты, чтобы UTF-8 не давал отрицательных char.
    const unsigned char *p=(const unsigned char *)domain;
    // Пояснение: do/while включает завершающий ноль домена; XOR смешивает байт, умножение обновляет хеш с
    // Пояснение: переполнением uint64_t.
    do {h=(h^*p)*UINT64_C(1099511628211);}while(*p++);
    // Пояснение: Продолжаем тем же хешем для байтов описания без его завершающего нуля.
    for(p=(const unsigned char *)description;*p;p++)h=(h^*p)*UINT64_C(1099511628211);
    // Пояснение: Возвращаем отпечаток, который обнаруживает изменение домена или описания.
    return h;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Освобождаем плоский массив векторов и обнуляем структуру индекса.
void embedding_free(Embedding *e) {free(e->vectors);memset(e,0,sizeof *e);}
// Пояснение: Загружает и проверяет индекс .uremb против конкретной таблицы CSV.
bool embedding_read(const char *path,const Table *t,Embedding *e,char err[ERR_SIZE]) {
    // Пояснение: Обнуляем индекс и читаем файл; при ошибке чтения возвращаем false.
    memset(e,0,sizeof *e);size_t n;char *raw=read_bytes(path,&n,err);if(!raw)return false;
    // Пояснение: Используем беззнаковые байты для безопасной распаковки чисел.
    const unsigned char *p=(const unsigned char *)raw;
    // Пояснение: Одна запись занимает 8 байтов хеша и 384 координаты по 4 байта.
    const size_t record=8+4*EMBEDDING_DIM;
    // Пояснение: Проверяем минимум 16 байтов, сигнатуру формата и размерность в заголовке; || продолжает
    // Пояснение: условие ниже.
    if(n<16||memcmp(p,"UREMB01\n",8)||little32(p+12)!=EMBEDDING_DIM||
       // Пояснение: Проверяем наличие заголовка CSV, число сайтов, отсутствие переполнения размера и точную
       // Пояснение: длину файла.
       !t->count||little32(p+8)!=t->count-1||t->count-1>(SIZE_MAX-16)/record||n!=16+(t->count-1)*record) {
        // Пояснение: Некорректный формат отклоняем и освобождаем исходные байты.
        snprintf(err,ERR_SIZE,"Неверный формат индекса или число записей. Пересоздайте индекс для этой таблицы.");free(raw);return false;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Выделяем непрерывный массив count×384 float; нулевая строка зарезервирована под заголовок
    // Пояснение: Table.
    e->count=t->count;e->vectors=mem_alloc(t->count*EMBEDDING_DIM*sizeof(float));
    // Пояснение: Пропускаем 16-байтный заголовок индекса.
    p+=16;
    // Пояснение: Идём по записям CSV с 1 и одновременно по бинарным блокам индекса.
    for(size_t r=1;r<t->count;r++,p+=record) {
        // Пояснение: Склеиваем две 32-битные половины в один 64-битный отпечаток.
        uint64_t hash=(uint64_t)little32(p)|(uint64_t)little32(p+4)<<32;
        // Пояснение: Сверяем отпечаток файла с текущими доменом и описанием той же записи.
        if(hash!=fingerprint(cell(t,r,DOMAIN),cell(t,r,DESCRIPTION))) {
            // Пояснение: При устаревшем индексе выдаём номер записи и переходим к общей очистке.
            snprintf(err,ERR_SIZE,"Индекс устарел: домен или описание записи %zu изменены. Пересоздайте индекс.",r);goto fail;
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: Находим начало вектора записи r; norm накапливает квадрат его длины с точностью double.
        float *v=e->vectors+r*EMBEDDING_DIM;double norm=0;
        // Пояснение: Проверяем каждую из 384 координат.
        for(size_t d=0;d<EMBEDDING_DIM;d++) {
            // Пояснение: Читаем биты float как uint32_t и копируем через memcpy, избегая нарушения правил
            // Пояснение: aliasing C.
            uint32_t bits=little32(p+8+d*4);memcpy(v+d,&bits,4);
            // Пояснение: NaN, бесконечность и координаты существенно за пределами [-1,1] недопустимы.
            if(!isfinite(v[d])||fabsf(v[d])>1.001f)goto invalid_vector;
            // Пояснение: Суммируем квадраты координат: это квадрат евклидовой нормы.
            norm+=(double)v[d]*v[d];
        // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
        }
        // Пояснение: Разрешаем нулевой вектор пустого описания; остальные должны иметь квадрат нормы около 1 с
        // Пояснение: допуском .02.
        if(norm!=0&&fabs(norm-1)>.02)goto invalid_vector;
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Все векторы проверены: байты файла больше не нужны.
    free(raw);return true;
// Пояснение: Ветка ошибки числовых данных вектора.
invalid_vector:
    // Пояснение: Сообщаем о повреждении индекса.
    snprintf(err,ERR_SIZE,"Индекс повреждён: неверный вектор.");
// Пояснение: Общая ветка освобождения для устаревшего или повреждённого индекса.
fail:
    // Пояснение: Освобождаем и байты, и частично заполненный массив векторов; возвращаем false.
    free(raw);embedding_free(e);return false;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
// Пояснение: Находит не более capacity похожих проверенных записей, заполняя hits по убыванию сходства.
size_t embedding_search(const Embedding *e,const Table *t,size_t row,EmbeddingHit *hits,size_t capacity) {
    // Пояснение: Без подходящего индекса, допустимого номера записи или места для результатов возвращаем 0.
    if(!e||!e->vectors||e->count!=t->count||!row||row>=t->count||!capacity)return 0;
    // Пояснение: q указывает на 384 координаты текущего сайта; norm пока равна нулю.
    const float *q=e->vectors+row*EMBEDDING_DIM;float norm=0;
    // Пояснение: Считаем квадрат длины вектора запроса.
    for(size_t d=0;d<EMBEDDING_DIM;d++)norm+=q[d]*q[d];
    // Пояснение: Нулевой вектор не несёт описания, поэтому искать по нему нечего.
    if(norm==0)return 0;
    // Пояснение: Пока результатов нет.
    size_t count=0;
    // Пояснение: Перебираем сайты, пропуская нулевую запись заголовка.
    for(size_t r=1;r<t->count;r++) {
        // Пояснение: Берём актуальный action из таблицы: новая ручная разметка участвует без перестроения
        // Пояснение: индекса.
        const char *a=cell(t,r,ACTION);
        // Примеры категорий: OK либо ERROR с исправленным label; NOT_DESC не подтверждает категорию.
        bool ok=!strcmp(a,"OK"),corrected=!strcmp(a,"ERROR")&&*cell(t,r,LABEL);
        // Пропускаем сам запрос, недостаточные описания и решения без установленной категории.
        if(r==row||(!ok&&!corrected)||(ok&&!*cell(t,r,CLASS)&&!*cell(t,r,LABEL)))continue;
        // Пояснение: Берём вектор кандидата; dot — скалярное произведение, vnorm — квадрат его длины.
        const float *v=e->vectors+r*EMBEDDING_DIM;float dot=0,vnorm=0;
        // Пояснение: Одним циклом считаем сумму q[d]×v[d] и сумму квадратов v[d].
        for(size_t d=0;d<EMBEDDING_DIM;d++){dot+=q[d]*v[d];vnorm+=v[d]*v[d];}
        // Пояснение: Пропускаем кандидатов с нулевым вектором.
        if(vnorm==0)continue;
        // Пояснение: Косинус = скалярное произведение / произведение длин; ограничиваем погрешности диапазоном
        // Пояснение: [-1,1].
        float score=fmaxf(-1,fminf(1,dot/sqrtf(norm*vnorm)));
        // Пояснение: Ищем позицию вставки после всех результатов с не меньшим score.
        size_t pos=0;while(pos<count&&hits[pos].score>=score)pos++;
        // Пояснение: Кандидат хуже уже набранного лимита: не включаем его.
        if(pos>=capacity)continue;
        // Пояснение: Увеличиваем число результатов, только пока есть свободное место.
        if(count<capacity)count++;
        // Пояснение: Сдвигаем хвост справа налево; при заполненном списке худший результат выпадает.
        for(size_t i=count-1;i>pos;i--)hits[i]=hits[i-1];
        // Пояснение: Вставляем номер записи и её сходство в найденную позицию.
        hits[pos]=(EmbeddingHit){r,score};
    // Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
    }
    // Пояснение: Возвращаем фактическое число заполненных элементов hits.
    return count;
// Пояснение: Конец текущего блока: функции, цикла или условной ветки, открытого фигурной скобкой.
}
